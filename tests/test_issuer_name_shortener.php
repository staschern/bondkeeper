<?php

declare(strict_types=1);

/**
 * Офлайн-проверка IssuerNameShortener (11 сентября 2026) — чистая
 * текстовая логика, не касается БД вообще, полностью тестируема без
 * SQLite/MySQL.
 *
 * Запуск (из корня репозитория, с этим файлом в tests/):
 *   php -d extension=mbstring tests/test_issuer_name_shortener.php
 *
 * На боевом сервере (с полным набором расширений PHP) флаг -d не нужен.
 */

require dirname(__DIR__) . '/bin/bootstrap.php';

use BondKeeper\Iss\IssuerNameShortener;

$failures = 0;
$checks = 0;

function check(string $label, string $expected, string $actual): void
{
    global $failures, $checks;
    $checks++;
    if ($expected === $actual) {
        echo "  OK   {$label}\n";
    } else {
        $failures++;
        echo "  FAIL {$label}\n       ожидали: {$expected}\n       получили: {$actual}\n";
    }
}

// --- Базовые формы, ровно как в примерах пользователя ---
check(
    'ПАО, кавычки-ёлочки, вложенные',
    'ПАО «НК «Роснефть»»',
    IssuerNameShortener::shorten('Публичное акционерное общество «НК «Роснефть»»')
);
check(
    'ООО, прямые кавычки',
    'ООО "Ромашка"',
    IssuerNameShortener::shorten('Общество с ограниченной ответственностью "Ромашка"')
);
check(
    'ЗАО',
    'ЗАО «Старый Формат»',
    IssuerNameShortener::shorten('Закрытое акционерное общество «Старый Формат»')
);
check(
    'НПАО',
    'НПАО «Тинькофф Банк»',
    IssuerNameShortener::shorten('Непубличное акционерное общество «Тинькофф Банк»')
);
check(
    'Голое АО (без "публичное/закрытое/непубличное")',
    'АО «Рога и копыта»',
    IssuerNameShortener::shorten('Акционерное общество «Рога и копыта»')
);
check(
    'Государственная корпорация -> ГК',
    'ГК «Ростех»',
    IssuerNameShortener::shorten('Государственная корпорация «Ростех»')
);
check(
    'Государственная компания -> тоже ГК',
    'ГК «Автодор»',
    IssuerNameShortener::shorten('Государственная компания «Автодор»')
);
check(
    'Международная компания -> МК',
    'МК «Технологии»',
    IssuerNameShortener::shorten('Международная компания «Технологии»')
);
check(
    'Министерство финансов -> Минфин (не акроним из заглавных, ровно как задано)',
    'Минфин Российской Федерации',
    IssuerNameShortener::shorten('Министерство финансов Российской Федерации')
);

// --- Комбинации ОПФ подряд (порядок слов сохраняется, не хардкод) ---
check(
    'Комбинация МК + ПАО, ровно как в примере пользователя',
    'МК ПАО «Технологии»',
    IssuerNameShortener::shorten('Международная компания публичное акционерное общество «Технологии»')
);

// --- Регистр ---
check(
    'Полностью капсом на входе',
    'ПАО «СБЕРБАНК»',
    IssuerNameShortener::shorten('ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО «СБЕРБАНК»')
);
check(
    'Полностью строчными на входе',
    'ООО «ромашка»',
    IssuerNameShortener::shorten('общество с ограниченной ответственностью «ромашка»')
);
check(
    'Смешанный регистр на входе (Title Case только у первого слова)',
    'ПАО «Газпром»',
    IssuerNameShortener::shorten('Публичное Акционерное Общество «Газпром»')
);

// --- Остаток строки не трогаем никак ---
check(
    'Регистр внутри кавычек сохраняется как в источнике (не приводим к единому виду)',
    'ПАО «НК «РОСНЕФТЬ»»',
    IssuerNameShortener::shorten('Публичное акционерное общество «НК «РОСНЕФТЬ»»')
);
check(
    'Слово между ОПФ и кавычками (например "Управляющая компания") остаётся как есть',
    'ООО Управляющая компания «Тройка Диалог»',
    IssuerNameShortener::shorten('Общество с ограниченной ответственностью Управляющая компания «Тройка Диалог»')
);

// --- Ничего не узнано — строка не трогается вообще ---
check(
    'Иностранный SPV без узнаваемой ОПФ — не трогаем',
    'RZD Capital P.L.C.',
    IssuerNameShortener::shorten('RZD Capital P.L.C.')
);
check(
    'Служебная заглушка SecuritiesImporter (нет emitent_title)',
    'MOEX-12345',
    IssuerNameShortener::shorten('MOEX-12345')
);
check(
    'Пустая строка не падает',
    '',
    IssuerNameShortener::shorten('')
);

// --- Границы слов: не должно ложно матчиться на похожее слово ---
check(
    '"общество" не матчится как часть более длинного слова ("Обществознание Инвест")',
    'Обществознание Инвест',
    IssuerNameShortener::shorten('Обществознание Инвест')
);

// --- Лишние пробелы в источнике ---
check(
    'Двойные пробелы между словами ОПФ схлопываются',
    'ПАО «Тест»',
    IssuerNameShortener::shorten('Публичное  акционерное   общество  «Тест»')
);

// --- Второй реальный формат ИСС: ОПФ хвостом в скобках, не префиксом ---
// Найдено на боевых данных 13 сентября 2026 (уже после пакета от 11
// сентября) — Газпромбанк отдаётся ИСС именно так, не "ОПФ «Название»".
check(
    'Газпромбанк — реальный формат "Название" (ОПФ), не ОПФ-префикс',
    'АО "Газпромбанк"',
    IssuerNameShortener::shorten('"Газпромбанк" (Акционерное общество)')
);
check(
    'Хвостовая ОПФ регистронезависима, кавычки-ёлочки тоже',
    'ПАО «Сбербанк»',
    IssuerNameShortener::shorten('«Сбербанк» (ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО)')
);
check(
    'Скобки в конце, но НЕ ОПФ — не трогаем (не гадаем)',
    'ООО "Ромашка (2)"',
    IssuerNameShortener::shorten('ООО "Ромашка (2)"')
);
check(
    // Известное неидеальное исключение (см. докблок класса): "акционерная
    // компания" — не в словаре (не то же самое, что "международная
    // компания" или "акционерное общество"), поэтому остаётся как есть,
    // но хвостовая ОПФ всё равно сокращается и переносится вперёд.
    'АЛРОСА — ведущая фраза "акционерная компания" вне словаря, хвостовая ОПФ сокращается',
    'ПАО Акционерная компания «АЛРОСА»',
    IssuerNameShortener::shorten('Акционерная компания «АЛРОСА» (публичное акционерное общество)')
);

echo "\n";
if ($failures === 0) {
    echo "ВСЕ {$checks} ПРОВЕРОК ПРОШЛИ.\n";
    exit(0);
}
echo "{$failures} ИЗ {$checks} ПРОВЕРОК ПРОВАЛЕНО.\n";
exit(1);
