-- =====================================================================
-- BondKeeper — миграция 033: блокировки ФНС — ожидание подтверждения
--
-- Сервис ФНС временами отдаёт по эмитенту не все строки или ни одной, а
-- через несколько часов или на следующий рабочий день — снова прежние
-- (на бою 09–13.10.2026: у трёх эмитентов четыре ложных «блокировка
-- снята» и четыре скачка числа счетов). Решение пользователя от
-- 13.10.2026: снятие блокировки и изменение числа счетов объявляются
-- только после подтверждения — если та же картина держится до первой
-- проверки следующего рабочего дня.
--
-- В fns_blocks остаётся ПОДТВЕРЖДЁННОЕ состояние (is_fns_blocked,
-- active_bank_count). Расхождение, которое ждёт подтверждения:
--   pending_bank_count — сколько счетов показал сервис (0 — блокировок
--                        нет); NULL — ничего не ждём;
--   pending_since      — день (по Москве), когда расхождение замечено.
-- Подробнее — докблок src/Fns/FnsBlocksImporter.php.
--
-- Существующие строки не меняются. Повторный запуск: «Duplicate column
-- name 'pending_bank_count'» — значит, миграция уже применена.
-- =====================================================================

ALTER TABLE fns_blocks
    ADD COLUMN pending_bank_count SMALLINT UNSIGNED NULL AFTER active_bank_count,
    ADD COLUMN pending_since DATE NULL AFTER pending_bank_count;
