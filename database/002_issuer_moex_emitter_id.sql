-- =====================================================================
-- BondKeeper — миграция 002: ИНН эмитента не отдаётся ISS API Мосбиржи
--
-- Проверено на реальном сервере (bondkeeper.ru), а не в теории:
--   1. Блок description по бумаге (/iss/securities/{ISIN}.json) не содержит
--      ни ИНН, ни структурированного названия юрлица-эмитента — только
--      EMITTER_ID (внутренний числовой ID эмитента на Мосбирже).
--   2. /iss/emitents.json?emitent_id=... — 404 (генерик-страница MOEX, не JSON).
--   3. /iss/index.json (официальный самоописывающий список ресурсов ISS
--      API) содержит ровно 8 групп: engines, markets, boards, boardgroups,
--      durations, securitytypes, securitygroups, securitycollections —
--      ресурса вида "эмитенты"/"компании" в ISS API нет вообще.
--
-- Итог: 3061 бумага из первого прогона seed_market.php была пропущена
-- целиком, потому что issuers.inn был обязательным полем, а взять ИНН
-- было неоткуда. Решение — не блокировать импорт бумаг отсутствующим ИНН:
-- EMITTER_ID достаточно стабилен и уникален на эмитента, чтобы быть
-- естественным ключом уже сейчас, а ИНН становится полем для отдельного
-- дообогащения (например, сверкой с e-disclosure.ru — тоже бесплатный
-- источник, но это отдельная, самостоятельная задача).
-- =====================================================================

ALTER TABLE issuers
    ADD COLUMN moex_emitter_id INT UNSIGNED NULL AFTER id,
    ADD UNIQUE KEY uq_issuers_moex_emitter_id (moex_emitter_id),
    MODIFY COLUMN inn VARCHAR(12) NULL;

-- UNIQUE KEY uq_issuers_inn (inn) из 001_schema.sql остаётся как есть:
-- уникальный индекс в MySQL допускает сколько угодно строк с inn = NULL
-- (NULL не считается равным NULL), так что несколько эмитентов без
-- сопоставленного ИНН друг другу не мешают.
