-- =====================================================================
-- BondKeeper — миграция 015: rating_actions под скользящее окно новостей
--
-- Пользователь уточнил цель парсинга новостей: не разовая догрузка
-- истории, а скрипт на cron каждые ~30 минут, который каждый раз
-- смотрит только последние новости (now() минус N часов, по умолчанию
-- 6 — с запасом, чтобы пропущенный/опоздавший прогон не потерял
-- новость) и либо добавляет, либо ОБНОВЛЯЕТ уже сохранённую запись
-- (вдруг агентство отредактировало пресс-релиз). Из этого — три правки:
--
--   1. Ключ апсерта меняется с (issuer_id, agency, action_date) на
--      ссылку конкретного пресс-релиза (source_url) — по ней
--      однозначно понятно, "это та же самая новость или другая", в
--      отличие от даты+эмитента (даже в рамках уже реализованного кода
--      бывает несколько действий в один день на одного эмитента).
--   2. issuer_id и rating_to становятся NULLABLE: по прямому указанию
--      пользователя, если сущность/уровень рейтинга не распознались —
--      новость всё равно должна записаться (с null в непонятных полях),
--      а не потеряться молча. Раньше такие строки просто не писались.
--   3. Новые поля has_unresolved_fields (флаг "нужен ручной просмотр")
--      и unresolved_fields (какие именно поля не распознались) — для
--      ручной проверки пользователем отдельно от автоматического потока.
-- =====================================================================

ALTER TABLE rating_actions
    MODIFY COLUMN issuer_id BIGINT UNSIGNED NULL,
    MODIFY COLUMN rating_to VARCHAR(20) NULL,
    ADD COLUMN has_unresolved_fields BOOLEAN NOT NULL DEFAULT FALSE AFTER source_url,
    ADD COLUMN unresolved_fields VARCHAR(255) NULL AFTER has_unresolved_fields,
    DROP KEY uq_rating_actions_issuer_agency_date,
    ADD UNIQUE KEY uq_rating_actions_source_url (source_url);
