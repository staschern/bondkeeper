-- BondKeeper — миграция 028: тип события «часть суммы пришла до срока»
-- (Этап 5, 5 октября 2026 — см. docs/STAGE5_PAYMENTS.md)
--
-- По реальным сообщениям НРД (тестовый доступ, 18–30.09.2026) нашёлся
-- случай, которого не было в таксономии: эмитент до наступления срока
-- перевёл только часть суммы (ООО «ММЗ», купон 29.09.2026: 2,84 из 4,68,
-- деньги пришли 28.09). НРД пишет в сообщении «Исполнена в неполном объеме
-- до наступления срока» — нарушением это ещё не называет. Решение
-- пользователя (05.10.2026): сообщать клиенту сразу, но жёлтым, а не
-- красным; если остаток к сроку не придёт, НРД объявит техдефолт и уйдёт
-- красное B2.
--   B1a — частичная выплата до наступления срока (жёлтое, клиенту).
--
-- Заодно уточнено название B2a: проверка теперь одна, в 12:02 мск
-- следующего рабочего дня после выплаты (раньше — «к концу дня Т»).
--
-- Повторный запуск безопасен.
-- =====================================================================

INSERT INTO event_types (code, group_code, name_ru, primary_source, default_priority, is_derived, notify_client, is_active) VALUES
('B1a', 'B', 'Частичная выплата до наступления срока',                                  'nsd',           'yellow', FALSE, TRUE, TRUE),
('B2a', 'B', 'Нет сообщения НРД о получении денег к полудню следующего рабочего дня', 'internal_calc', 'yellow', TRUE,  TRUE, TRUE)
ON DUPLICATE KEY UPDATE
    group_code = VALUES(group_code),
    name_ru = VALUES(name_ru),
    primary_source = VALUES(primary_source),
    default_priority = VALUES(default_priority),
    is_derived = VALUES(is_derived),
    notify_client = VALUES(notify_client),
    is_active = VALUES(is_active);
