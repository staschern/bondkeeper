-- =====================================================================
-- BondKeeper — миграция 006: coupons/amortizations перестают "замерзать"
--
-- Найдено вживую: обе таблицы перестали обновляться после первого
-- прогона. Причина — комбинация двух решений в BondizationImporter:
--
--   1. Отбор "что обрабатывать сегодня" был вида "LEFT JOIN coupons ...
--      WHERE c.id IS NULL" — то есть буквально "нет вообще ни одной
--      строки". Как только у бумаги появляется хотя бы одна строка
--      (даже одна купонная выплата из сотен), бумага навсегда выпадает
--      из ежедневной обработки — cron её больше не открывает.
--   2. `value_per_bond NOT NULL` заставлял `continue`-пропускать любую
--      выплату, для которой API ещё не знает точную сумму (типичный
--      случай — флоатеры и структурные облигации: сумма будущего купона
--      зависит от ещё не наступившей даты фиксации базовой ставки).
--      Строка в этом случае не создавалась вообще — не "NULL", а
--      отсутствие факта, что купон существует и его дата известна.
--
-- Вместе это значит: у флоатера/структурной облигации первая же строка
-- (обычно уже прошедший купон с известной суммой) блокирует бумагу от
-- дальнейшей обработки навсегда — при этом будущие купоны, для которых
-- сумма ещё не известна, никогда не попадут в таблицу, потому что
-- бумага больше не открывается.
--
-- Дополнительно: `coupon_number` считался нами же (порядковый номер
-- после сортировки по дате), а не приходил из API. Раньше это заставляло
-- держать DELETE+INSERT вместо апсерта — если API возвращал МЕНЬШЕ строк
-- (типичная ситуация), апсерт по (security_id, coupon_number) не мог
-- корректно найти и убрать "лишние" номера. Переход на естественный ключ
-- (security_id, period_end_date) снимает эту проблему полностью — дата
-- не "сдвигается" от прогона к прогону, в отличие от порядкового номера.
-- =====================================================================

-- value_per_bond остаётся DECIMAL(18,4), а не (12,4) — миграция 003 уже
-- расширяла эту колонку (100 000 000 ₽ на бумагу у части институциональных
-- размещений не влезает в (12,4)). Здесь меняем только nullability, а не
-- точность/разрядность — сужение обратно до (12,4) роняет ALTER на
-- реальных данных с "Out of range value" (найдено вживую на bondkeeper.ru
-- при накатке этой миграции).
ALTER TABLE coupons
    DROP KEY uq_coupons_security_number,
    DROP COLUMN coupon_number,
    MODIFY COLUMN value_per_bond DECIMAL(18,4) NULL,
    ADD UNIQUE KEY uq_coupons_security_period_end (security_id, period_end_date);

ALTER TABLE amortizations
    MODIFY COLUMN value_per_bond DECIMAL(18,4) NULL,
    ADD UNIQUE KEY uq_amortizations_security_period (security_id, payment_date_planned);
