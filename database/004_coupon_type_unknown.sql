-- =====================================================================
-- BondKeeper — миграция 004: coupon_type не должен молча угадывать 'fixed'
--
-- Найдено на реальных данных (bondkeeper.ru, август 2026): поле BOND_TYPE
-- из ISS API — это не таксономия "тип купона", а тег САМОЙ ЗАМЕТНОЙ
-- особенности бумаги, и она бывает разной природы:
--   - "Фикс с известным купоном"    — про характер ставки (единственный
--                                      случай, где можно уверенно сказать
--                                      coupon_type = 'fixed')
--   - "Амортизируемые облигации"    — про структуру погашения (например,
--                                      ипотечные облигации ДОМ.РФ)
--   - "Валютные облигации"          — про валюту номинала; один из
--                                      наблюдавшихся примеров с такой
--                                      меткой оказался вдобавок ещё и
--                                      бессрочной облигацией
--                                      (BOND_SUBTYPE = "Бессрочные")
-- Прежняя эвристика (SecuritiesImporter::mapCouponType) молча считала
-- coupon_type = 'fixed' по умолчанию, если не находила явных признаков
-- floating/indexed/zero_coupon — то есть подменяла "не знаю" на "фикс".
-- Практическое следствие: 179 купонов у 46 бумаг этого типа оказались без
-- rate_percent в coupons, при этом бумага была помечена как 'fixed', где
-- ставка вроде бы обязана быть известна всегда — расследование показало,
-- что дело не в баге импорта купонов, а в неверной классификации бумаги.
--
-- Добавляем 'unknown' — теперь мы честно говорим "не удалось определить"
-- вместо того, чтобы угадывать.
-- =====================================================================

ALTER TABLE securities
    MODIFY COLUMN coupon_type ENUM('fixed','floating','indexed','zero_coupon','unknown') NOT NULL DEFAULT 'unknown';
