-- =====================================================================
-- BondKeeper — миграция 007: initial_nominal_value — неизменная база для
-- расчёта остатка номинала в redemptions
--
-- Найдено вживую: redemptions.value_per_bond считался как
--   securities.nominal_value (ТЕКУЩИЙ, живой номинал — тот же FACEVALUE,
--   который синкается ежедневно и у амортизируемой бумаги УЖЕ САМ ПО СЕБЕ
--   является остатком после прошлых амортизаций)
--   МИНУС SUM(amortizations.value) по ВСЕЙ амортизации целиком —
--   bondization отдаёт график сразу и прошлые, и будущие транши.
--
-- Прошлая амортизация вычиталась дважды: один раз неявно (её уже нет в
-- текущем FACEVALUE) и один раз явно (она есть в сумме) — и вдобавок
-- вычиталась вся ещё не наступившая будущая амортизация. У бумаги с
-- существенной историей амортизации расчёт легко уходит в минус.
--
-- Правильная формула: value_per_bond = НЕИЗМЕННЫЙ номинал на момент
-- выпуска минус SUM(вся амортизация, прошлая и будущая) — вычитается
-- ровно один раз, из фиксированной базы. Текущий nominal_value для этой
-- формулы не годится, потому что сам меняется со временем — нужна
-- отдельная колонка, зафиксированная раз и навсегда при первой вставке
-- бумаги (заполняется в SecuritiesImporter, приоритет INITIALFACEVALUE
-- над FACEVALUE — обратный порядку для nominal_value, где нужен текущий
-- номинал; НЕ входит в ON DUPLICATE KEY UPDATE — по тому же принципу,
-- что и created_at, иначе каждый ежедневный синк тихо переписывал бы её
-- текущим FACEVALUE и вся идея теряла бы смысл).
-- =====================================================================

ALTER TABLE securities
    ADD COLUMN initial_nominal_value DECIMAL(15,2) NULL AFTER nominal_value;
