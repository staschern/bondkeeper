-- =====================================================================
-- BondKeeper — миграция 027: типы событий для уведомлений о выплатах
-- (Этап 5, 4 октября 2026 — см. docs/STAGE5_PAYMENTS.md)
--
-- Таксономия A1–E3 засеяна с миграции 001; для схемы уведомлений о
-- выплатах, согласованной с пользователем 04.10.2026, не хватало двух
-- типов:
--   R1  — напоминание о предстоящей выплате (купон, амортизация,
--         погашение): по умолчанию за сутки до даты выплаты по графику,
--         чтобы клиент успел продать бумагу до выплаты, если не хочет
--         держать. Считаем сами (internal_calc), уведомляем клиента.
--   B2b — «нет никаких сообщений НРД на следующий рабочий день после
--         выплаты»: по словам пользователя, это странно и похоже на
--         технический сбой — уведомление только администратору
--         (notify_client = FALSE), клиенту не показывается.
-- Остальные типы схемы уже есть: A2/A4/A6 («получено НРД» — выплата
-- состоялась), A3/A5/A7 («передано депонентам»), B1, B2, B2a, B4, B5.
--
-- Повторный запуск безопасен.
-- =====================================================================

INSERT INTO event_types (code, group_code, name_ru, primary_source, default_priority, is_derived, notify_client, is_active) VALUES
('R1',  'R', 'Напоминание о предстоящей выплате',                        'internal_calc', 'info',   TRUE, TRUE,  TRUE),
('B2b', 'B', 'Нет сообщений НРД на следующий рабочий день после выплаты', 'internal_calc', 'yellow', TRUE, FALSE, TRUE)
ON DUPLICATE KEY UPDATE
    group_code = VALUES(group_code),
    name_ru = VALUES(name_ru),
    primary_source = VALUES(primary_source),
    default_priority = VALUES(default_priority),
    is_derived = VALUES(is_derived),
    notify_client = VALUES(notify_client),
    is_active = VALUES(is_active);
