-- =====================================================================
-- BondKeeper — миграция 018: статус "на пересмотре" (CreditWatch/Rating
-- Watch) как значения ENUM outlook
--
-- По решению пользователя (сентябрь 2026) — расширяем словарь ENUM
-- outlook (rating_actions.outlook_from/outlook_to, current_ratings.outlook)
-- шестью новыми значениями вместо отдельного столбца/таблицы: раз речь
-- идёт именно о "варианте прогноза", а не о принципиально новой сущности,
-- пользователь предпочёл держать это в том же поле.
--
-- Единый формат имён — under_review + суффикс направления/базового
-- прогноза:
--
--   under_review            — на пересмотре, направление не указано
--                              (НКР: "рейтинг на пересмотре" без уточнения;
--                               НРА: "Без прогноза - под наблюдением")
--   under_review_negative   — на пересмотре с возможностью понижения (НКР)
--   under_review_positive   — на пересмотре с возможностью повышения (НКР)
--   under_review_stable     — на пересмотре, прогноз был "стабильный"
--                              (НРА: "Стабильный - под наблюдением")
--   under_review_developing — на пересмотре, прогноз был "развивающийся"
--                              (НРА: "Развивающийся - под наблюдением")
--   review_concluded        — пересмотр завершён/статус наблюдения снят
--                              (НРА: "Без прогноза - снято с наблюдения").
--                              Пользователь явно подтвердил: это
--                              ОТДЕЛЬНОЕ значение, не NULL — статус
--                              "было снято с наблюдения именно этим
--                              действием" сам по себе значим, даже когда
--                              текущий прогноз после этого не указан.
--
-- Источники (см. docs/STAGE3_RATINGS.md):
--   - НКР: свободный текст заголовка пресс-релиза ("на пересмотре",
--     "с возможностью понижения/повышения") — глагол "изменило" добавлен
--     в список распознаваемых (см. NkrTitleParser::VERBS) специально ради
--     заголовков вида "НКР изменило прогноз... на «рейтинг на
--     пересмотре...»", где сам грейд не называется вовсе.
--   - НРА: РЕАЛЬНАЯ структурированная колонка "Под наблюдением" в
--     Excel-выгрузке (значения "", "Под наблюдением", "Снято с
--     наблюдения") — не текстовый разбор, надёжнее, чем у НКР.
--   - Эксперт РА: своя терминология свободного текста ("установил"/
--     "продлил"/"снял статус «под наблюдением»") — направление в этой
--     формулировке на практике не встречается, только голое under_review.
--
-- MySQL ALTER TABLE ... MODIFY COLUMN на ENUM — добавление новых значений
-- в конец списка безопасно для существующих строк (старые значения не
-- меняют своих числовых кодов), но требует ПОЛНОГО перечисления всех
-- значений заново (MySQL не поддерживает "ADD VALUE" для ENUM, в отличие
-- от PostgreSQL).
-- =====================================================================

ALTER TABLE rating_actions
    MODIFY COLUMN outlook_from ENUM(
        'positive','stable','negative','developing',
        'under_review','under_review_negative','under_review_positive',
        'under_review_stable','under_review_developing','review_concluded'
    ) NULL,
    MODIFY COLUMN outlook_to ENUM(
        'positive','stable','negative','developing',
        'under_review','under_review_negative','under_review_positive',
        'under_review_stable','under_review_developing','review_concluded'
    ) NULL;

ALTER TABLE current_ratings
    MODIFY COLUMN outlook ENUM(
        'positive','stable','negative','developing',
        'under_review','under_review_negative','under_review_positive',
        'under_review_stable','under_review_developing','review_concluded'
    ) NULL;
