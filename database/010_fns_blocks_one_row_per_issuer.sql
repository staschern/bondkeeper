-- =====================================================================
-- BondKeeper — миграция 010: fns_blocks — одна строка на эмитента
--
-- Найдено на реальных данных (ООО "Контрол Лизинг", ИНН 7805485840):
-- одна и та же непрерывная блокировка по налоговой задолженности
-- периодически переиздаётся ФНС под НОВЫМ номером решения (даже когда
-- банк, сумма и основание не меняются) — например №2395737 сменился на
-- №2454390 в одном из банков без какого-либо реального разблокирования
-- между ними. Ключ (issuer_id, bank_bik, decision_number) из миграции
-- 008 воспринял это как "старое решение снято, новое создано" — вместо
-- одной обновлённой строки на банк накапливались дубли на каждую смену
-- номера решения.
--
-- Заодно оказалось, что для одного эмитента дата, сумма и основание
-- ОДИНАКОВЫ во всех строках независимо от банка (закономерно — это одна
-- и та же налоговая задолженность, просто приостановлены счета сразу во
-- всех банках, где они есть) — то есть построчное хранение по банкам не
-- несёт дополнительной информации, кроме количества самих банков.
--
-- Переходим на одну строку на эмитента: данные (дата, сумма, основание)
-- берутся из первой строки ответа, конкретные БИК банков не хранятся —
-- вместо них количество одновременно заблокированных банков
-- (active_bank_count). Старые построчные данные по банкам очищаются —
-- это тестовый объём (несколько эмитентов), проще пересобрать заново
-- обычным прогоном check_fns_blocks.php, чем писать миграцию-конвертер
-- для данных, которые всё равно устарели по факту (номера решений).
-- =====================================================================

DELETE FROM fns_blocks;

ALTER TABLE fns_blocks
    DROP KEY uq_fns_blocks_issuer_bank_decision;

ALTER TABLE fns_blocks
    CHANGE COLUMN bank_bik active_bank_count SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    ADD UNIQUE KEY uq_fns_blocks_issuer (issuer_id);
