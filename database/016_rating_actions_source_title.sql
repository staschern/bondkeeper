-- =====================================================================
-- BondKeeper — миграция 016: откат схемы миграции 015, source_title
--
-- Контекст (сентябрь 2026): параллельно с моей работой над скользящим
-- окном (миграция 015 — issuer_id/rating_to NULLABLE, ключ апсерта
-- source_url, has_unresolved_fields/unresolved_fields) шла независимая
-- разработка той же задачи в отдельном треке, доведённая до боевой
-- проверки на всех 4 агентствах (не только НКР/Эксперт РА). По решению
-- пользователя её архитектура принята как основная — она решает ТУ ЖЕ
-- проблему ("не терять пропущенные новости") другим способом: отдельный
-- журнал `rating_news_log` (миграция 017) вместо nullable-полей прямо в
-- rating_actions. Эта миграция откатывает 015 к состоянию миграции 014
-- и добавляет source_title (сырой заголовок пресс-релиза для аудита).
--
-- rating_actions снова хранит только ПОЛНОСТЬЮ распознанные действия
-- (issuer_id и rating_to обязательны) — таблица "истории решений", а не
-- "истории попыток разбора". Черновая/непонятая новость больше не
-- попадает сюда вовсе — она остаётся в rating_news_log с соответствующим
-- статусом (skipped_unmatched/skipped_no_grade/...) и автоматически
-- пробуется заново на каждом прогоне, пока не либо распознается, либо
-- останется так навсегда (осознанно, не потеряно — видно в логе).
--
-- === Шаг 1: убрать строки, у которых почти наверняка НЕТ шанса ===
--
-- Пользователь подтвердил: миграция 015 уже применена на бою, и
-- nkr-news/expert_ra-news уже реально запускались — значит, в
-- rating_actions вероятно есть строки с issuer_id IS NULL и/или
-- rating_to IS NULL (записанные по дизайну миграции 015 как "не удалось
-- распознать, но не терять"). Под новой моделью такие строки не имеют
-- смысла в ЭТОЙ таблице — то, что они пытались зафиксировать
-- (незавершённая попытка разбора), теперь по определению живёт в
-- rating_news_log, а не здесь. Удаляем их перед тем, как снова сделать
-- issuer_id/rating_to NOT NULL (иначе ALTER упадёт на существующих NULL).
-- Ничего не теряется: ссылка на пресс-релиз (source_url) НЕ была занесена
-- в rating_news_log (той таблицы ещё не существовало) — как только
-- появится миграция 017, следующий же прогон nkr-news/expert_ra-news
-- увидит эти пресс-релизы заново (в пределах своего окна --days) и
-- либо распознает их правильно, либо честно залогирует статус попытки.
--
-- === Шаг 2: разрешить дубли (issuer_id, agency, action_date) ===
--
-- Пока в силе был ключ по source_url (миграция 015), два РАЗНЫХ
-- пресс-релиза одного агентства для одного эмитента в один день могли
-- легитимно получить по отдельной строке (в отличие от миграции 014,
-- где такое "тихо перезаписывало" первую запись — сам этот компромисс
-- был явно задокументирован там). Перед восстановлением UNIQUE(issuer_id,
-- agency, action_date) такие дубли нужно свести к одной строке на
-- комбинацию — иначе ALTER TABLE упадёт на "Duplicate entry". Оставляем
-- ту, что обновлялась позже (source_title/created_at) — тот же самый
-- компромисс "вторая строка важнее", что уже был принят и
-- задокументирован в миграции 014, просто применяется здесь один раз
-- явно, а не молча при каждом апсерте.
-- =====================================================================

DELETE FROM rating_actions WHERE issuer_id IS NULL OR rating_to IS NULL;

DELETE FROM rating_actions WHERE id IN (
    SELECT id FROM (
        SELECT id,
               ROW_NUMBER() OVER (
                   PARTITION BY issuer_id, agency, action_date
                   ORDER BY created_at DESC, id DESC
               ) AS rn
        FROM rating_actions
    ) ranked
    WHERE rn > 1
);

ALTER TABLE rating_actions
    MODIFY COLUMN issuer_id BIGINT UNSIGNED NOT NULL,
    MODIFY COLUMN rating_to VARCHAR(20) NOT NULL,
    DROP COLUMN has_unresolved_fields,
    DROP COLUMN unresolved_fields,
    ADD COLUMN source_title VARCHAR(500) NULL AFTER source_url,
    DROP KEY uq_rating_actions_source_url,
    ADD UNIQUE KEY uq_rating_actions_issuer_agency_date (issuer_id, agency, action_date);
