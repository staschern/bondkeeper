-- =====================================================================
-- BondKeeper — миграция 022: сопоставление эмитента "по корню" названия
-- (SPV/материнская компания)
--
-- По прямому запросу пользователя (сентябрь 2026): материнская компания
-- и её SPV "для привлечения долга" по кредитному риску считаются РАВНЫМИ
-- — но до этой правки, если в issuers заведена только ОДНА из двух
-- сторон (например, только SPV "Ростелеком Финанс"), а источник
-- (новость агентства / его официальный список текущих рейтингов)
-- называет ТОЛЬКО ДРУГУЮ ("Ростелеком"), ни сопоставление по ИНН, ни
-- точное сопоставление по имени не находили эмитента — действие
-- полностью терялось для этого issuer_id.
--
-- Добавлен третий, последний уровень сопоставления —
-- IssuerMatcher::findIssuerIdByRootName() (по "корню" названия после
-- снятия ОПФ и типовых маркерных слов SPV "Финанс"/"Капитал",
-- применяется симметрично к обеим сторонам). Самый неточный из трёх
-- уровней — по решению пользователя, строка всё равно пишется как
-- обычно (не теряем данные), но помечается отдельным флагом для
-- выборочной проверки администратором (см. bin/seed_ratings.php).
--
-- Колонка добавлена в ОБЕ таблицы, которые может обновить такое
-- сопоставление: rating_actions (новости agencies-*-news + НРА) и
-- current_ratings (периодическая полная сверка НКР/Эксперт РА/АКРА +
-- НРА, см. STAGE3_RATINGS.md).
-- =====================================================================

ALTER TABLE rating_actions
    ADD COLUMN matched_by_root_name BOOLEAN NOT NULL DEFAULT FALSE AFTER source_title;

ALTER TABLE current_ratings
    ADD COLUMN matched_by_root_name BOOLEAN NOT NULL DEFAULT FALSE AFTER last_action_date;
