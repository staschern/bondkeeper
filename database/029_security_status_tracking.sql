-- =====================================================================
-- BondKeeper — миграция 029: статус бумаги начинает меняться
-- (11 октября 2026 — см. docs/SECURITY_STATUS.md)
--
-- До этой миграции securities.status ставился по умолчанию ('active') и
-- больше не менялся: на 11.10.2026 в базе числились активными 193 бумаги,
-- которых на бирже уже нет (169 погашены по сроку, 24 ушли до срока), и
-- ни одна бумага не была отмечена как техдефолтная или дефолтная.
--
-- Сами значения статуса не меняются (active, matured, tech_default,
-- default, delisted). Добавляются четыре служебные колонки:
--   status_reason     — почему стоит нынешний статус (код причины, см.
--                       BondKeeper\Securities\SecurityStatus);
--   status_changed_at — когда статус менялся последний раз;
--   ended_at          — дата, когда выпуск перестал существовать
--                       (погашен или ушёл с биржи); у бумаг в обращении
--                       пусто;
--   missing_since     — с какого дня бумаги нет в списке торгуемых на
--                       бирже. Нужна для отсрочки: бумага, пропавшая до
--                       срока погашения, меняет статус не в первый же
--                       день (решение пользователя, 11.10.2026).
--
-- ВНИМАНИЕ: повторный запуск выдаст ошибку «Duplicate column name» — это
-- значит, что миграция уже применена, делать ничего не нужно.
-- =====================================================================

ALTER TABLE securities
    ADD COLUMN status_reason     VARCHAR(40) NULL AFTER status,
    ADD COLUMN status_changed_at DATETIME    NULL AFTER status_reason,
    ADD COLUMN ended_at          DATE        NULL AFTER status_changed_at,
    ADD COLUMN missing_since     DATE        NULL AFTER ended_at;
