-- =====================================================================
-- BondKeeper — миграция 009: отслеживание попыток проверки блокировок ФНС
--
-- До этой миграции неудачная попытка проверки (капча, сетевая ошибка)
-- вообще не оставляла следа в БД — issuers.fns_last_checked_at
-- обновлялся только при УСПЕШНОЙ проверке, поэтому нельзя было отличить
-- "эмитента ещё ни разу не проверяли" от "проверяли, но не вышло, и
-- давно пора попробовать снова".
--
-- issuers.fns_last_checked_at переименован в last_success_verification —
-- смысл не поменялся (когда последний раз проверка реально удалась), имя
-- уточнено, чтобы не путать с новым date_verification (когда была
-- последняя ПОПЫТКА, вне зависимости от результата).
--
-- Отдельного поля "status" не заводим — issuers.is_fns_blocked уже
-- ровно это и есть (блокировка есть/нет), просто булево вместо ENUM.
-- fns_blocks не трогаем — таблица остаётся подробным логом по банкам/
-- решениям (см. миграцию 008), это по-прежнему нужно и работает.
-- =====================================================================

ALTER TABLE issuers
    CHANGE COLUMN fns_last_checked_at last_success_verification DATETIME NULL,
    ADD COLUMN verification ENUM('success', 'error') NULL AFTER is_fns_blocked,
    ADD COLUMN date_verification DATETIME NULL AFTER verification;
