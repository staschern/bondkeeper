-- =====================================================================
-- BondKeeper — миграция 005: is_mortgage_backed
--
-- Найдено при разборе проблемной бумаги RU000A0JQAM6 (ДОМ.РФ, серия А15,
-- документ documents/2026.08.10_BondKeeper_issuers_securities_QA.md):
-- у неё не выгружается полная история купонов в coupons — и это не баг
-- импорта. RU000A0JQAM6 — ипотечная ценная бумага (ИЦБ), выпущена через
-- SPV "ДОМ.РФ Ипотечный агент": купон = реально поступившие за период
-- платежи по пулу закладных за вычетом расходов агента, а не заранее
-- известная ставка. У ISS физически не может быть "полного графика
-- вперёд" для такой бумаги — будущие суммы не существуют как числа,
-- пока заёмщики не заплатят по ипотекам за соответствующий период.
--
-- Это не пробел биржи и не наш баг — так устроен инструмент. Флаг нужен,
-- чтобы продукт не показывал пользователю пустой/сломанный на вид график
-- там, где его структурно не может быть, а показывал понятное объяснение.
-- =====================================================================

ALTER TABLE securities
    ADD COLUMN is_mortgage_backed BOOLEAN NOT NULL DEFAULT FALSE AFTER is_structured;
