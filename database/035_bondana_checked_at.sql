-- =====================================================================
-- BondKeeper — миграция 035: securities.bondana_checked_at
-- (решения пользователя, 19–20.10.2026, docs/OFFERS.md)
--
-- Сплошная сверка с Bondana (18.10.2026, 3081 бумага) закрыла рынок на
-- тот момент целиком — повторять её не планируется. Дальше нужно только
-- проверять по Bondana НОВЫЕ бумаги (решение от 20.10.2026): бумаги с уже
-- выявленной офертой второй раз не трогаем.
--
-- bondana_checked_at — когда бумагу в последний раз включали в выгрузку
-- на сверку (bin/bondana_check_list.php) или подтверждали по готовому
-- результату (bin/bondana_check_apply.php). NULL — ещё ни разу.
--
-- Повторный запуск выдаст «Duplicate column name» — значит, применена.
-- =====================================================================

ALTER TABLE securities
    ADD COLUMN bondana_checked_at DATETIME NULL AFTER has_offer;

-- Бумаги, которые уже прошли сплошную сверку 18.10.2026 (весь рынок на тот
-- день), помечаются проверенными этой же датой — иначе список на следующую
-- сверку включил бы все 3081 бумагу заново. По created_at, а не «все
-- NULL на момент применения миграции» — если применить позже 18.10,
-- бумаги, заведённые seed_market.php уже ПОСЛЕ сверки, не должны
-- попасть в бэкафилл: они как раз и есть те «новые», которые нужно
-- проверить по Bondana в первую очередь.
UPDATE securities SET bondana_checked_at = '2026-10-18 00:00:00'
    WHERE bondana_checked_at IS NULL AND created_at <= '2026-10-18 23:59:59';
