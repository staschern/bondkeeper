-- =====================================================================
-- BondKeeper — миграция 023: явная связка "неизвестный ИНН → issuer_id"
--
-- По прямому запросу пользователя (сентябрь 2026): "по корню" названия
-- (миграция 022, слова-маркеры Финанс/Капитал/Групп) решает только
-- случай, когда одно название — это другое плюс типовое слово. Реальные
-- найденные случаи, где это НЕ так вообще (имена не имеют ничего
-- общего): ООО «АгроНэкст» (ИНН 2315190775) ↔ ООО «Русбонд-Удобрения»
-- (ИНН 9725091192); ООО «ЕВА» (ИНН 7708335695) ↔ ООО «ФСК Активы» (ИНН
-- 7714482955). Ни ИНН, ни точное имя, ни корень такие пары в принципе
-- связать не могут.
--
-- ВАЖНО про направление связки (уточнено пользователем не с первого
-- раза — стоит подчеркнуть явно): "spv_inn" — это НЕ обязательно "ИНН
-- SPV" в смысле реальной корпоративной структуры (кто чья "мать", а кто
-- SPV/поручитель). Единственный реальный критерий — spv_inn это ИНН
-- ТОЙ СТОРОНЫ, КОТОРОЙ НЕТ В issuers, а issuer_id — ТОЙ, ЧТО УЖЕ ЕСТЬ.
-- В примерах выше в issuers физически есть «Русбонд-Удобрения» и «ФСК
-- Активы» (у обеих облигации торгуются на бирже), а «АгроНэкст» и «ЕВА»
-- — НЕТ, хотя структурно именно они — материнские компании/поручители,
-- которых рейтингует агентство напрямую. Связки: spv_inn=2315190775
-- (АгроНэкст) → issuer_id «Русбонд-Удобрения»; spv_inn=7708335695
-- (ЕВА) → issuer_id «ФСК Активы». См. подробное объяснение в докблоке
-- IssuerMatcher::findIssuerIdBySpvLink().
--
-- Решение — та же философия, что уже есть у ManualRatingsImporter
-- ("то, что автоматика не может найти сама, добавляет человек"): явная,
-- вручную заведённая связка (spv_inn → issuer_id), которую
-- IssuerMatcher::findIssuerIdBySpvLink() проверяет СРАЗУ после
-- собственного ИНН кандидата (который, естественно, не находится в
-- issuers напрямую — иначе связка вообще не понадобилась бы) — это не
-- эвристика, а подтверждённый человеком факт, поэтому приоритет у неё
-- ВЫШЕ, чем у сопоставления по корню (миграция 022).
--
-- Одна связанная сторона — ровно один issuer_id (PRIMARY KEY на
-- spv_inn), но у одного issuer_id может быть НЕСКОЛЬКО таких связок —
-- это обычная практика (несколько разных юрлиц ссылаются на одну и ту
-- же реально отслеживаемую компанию).
-- =====================================================================

CREATE TABLE issuer_spv_links (
    spv_inn      VARCHAR(12)     NOT NULL,
    issuer_id    BIGINT UNSIGNED NOT NULL,
    spv_name     VARCHAR(500)    NULL,       -- для справки/аудита, в поиске не участвует
    note         VARCHAR(500)    NULL,
    created_at   DATETIME        NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (spv_inn),
    KEY idx_issuer_spv_links_issuer (issuer_id),
    CONSTRAINT fk_issuer_spv_links_issuer FOREIGN KEY (issuer_id) REFERENCES issuers(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
