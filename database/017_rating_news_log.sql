-- =====================================================================
-- BondKeeper — миграция 017: журнал просмотренных пресс-релизов
--
-- По прямому запросу пользователя (сентябрь 2026) — переход парсинга
-- новостей рейтинговых агентств на автоматическое расписание (каждые
-- 30 минут). Раньше инкрементальность держалась на MAX(action_date) уже
-- ЗАПИСАННЫХ действий (см. историю в NkrNewsImporter/ExpertRaNewsImporter)
-- — рабочая граница для редких ручных прогонов, но с документированным
-- изъяном: пресс-релиз, пропущенный из-за несопоставленного эмитента, сам
-- не пересматривался, пока не запускали --full (всю историю заново).
-- При частом автоматическом прогоне так делать нельзя — либо теряем
-- пропущенные действия навсегда, либо гоняем всю историю каждые 30 минут.
--
-- Решение: отдельный журнал по КАЖДОМУ увиденному пресс-релизу (не
-- только успешно записанным) — ключ дедупа, как и предложил пользователь,
-- URL пресс-релиза. НЕ переиспользуем UNIQUE-ключ rating_actions
-- (issuer_id, agency, action_date) — та таблица (после миграции 016)
-- в принципе не получает строку для несопоставленных релизов, ей нечем
-- их отследить.
--
-- status='matched' — пресс-релиз обработан окончательно, повторно не
-- трогаем никогда. Любой другой статус — пробуем снова на каждом
-- прогоне (в пределах окна по дате, см. NkrNewsImporter::import()) —
-- это и есть автоматическое решение проблемы "эмитента добавили в
-- issuers позже": пропущенное действие само подхватится на следующем
-- же 30-минутном прогоне, без ручного --full.
--
-- agency — не только для НКР: при подключении Эксперт РА/НРА (и позже
-- АКРА через почту) на то же расписание не потребуется новая миграция,
-- тот же журнал на всех.
-- =====================================================================

CREATE TABLE rating_news_log (
    id              BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    agency          ENUM('nra','acra','expert_ra','nkr') NOT NULL,
    source_url      VARCHAR(500) NOT NULL,
    action_date     DATE NOT NULL,
    status          ENUM('matched','skipped_not_rating','skipped_no_grade','skipped_unmatched','skipped_non_standard') NOT NULL,
    processed_at    DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uq_rating_news_log_agency_url (agency, source_url),
    KEY idx_rating_news_log_status (agency, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
