<?php

declare(strict_types=1);

namespace BondKeeper\Ratings;

/**
 * ШАБЛОН, сентябрь 2026 — разбор текста писем АКРА "Новое рейтинговое
 * действие" (рассылка с noreply@acra-ratings.ru, формат подтверждён на
 * ~15 реальных письмах, присланных пользователем). В отличие от НКР/НРА/
 * Эксперт РА — это НЕ проверено вживую против настоящего письма/ящика
 * (в песочнице нет доступа к IMAP и к самому ящику), только против
 * скопированных текстов писем (см. docs/STAGE3_RATINGS.md). Разработчику
 * нужно доверить регэкспы, но перепроверить на первом реальном прогоне —
 * особенно "непроверенные вживую" пункты ниже.
 *
 * === Формат одного действия ===
 *
 * Каждое действие в письме — одна строка вида:
 *   "<Подлежащее> — <текст действия>"
 * с длинным тире (—, U+2014), не дефисом. Подлежащее — либо чистое
 * название компании (иногда в кавычках: ПАО "МЕГАФОН", АО КБ "ПОЙДЁМ!"),
 * либо "Облигации <компания> серии <код> [(ISIN)]" для рейтинга
 * конкретного выпуска — ISIN присутствует НЕ ВСЕГДА даже для одного и
 * того же выпуска в разных письмах (см. STAGE3_RATINGS.md, находка про
 * Ростовскую область). Регионы/субъекты РФ и часть банков — без кавычек
 * ВООБЩЕ (та же категория, что и "не сопоставлено" у Эксперт РА).
 *
 * === Глаголы (проверено вживую) ===
 *   - подтверждён — подтверждение
 *   - присвоен (в т.ч. "присвоен ожидаемый рейтинг" — грейд с префиксом
 *     "e": eAAA(RU) — предварительный/ожидаемый рейтинг, не опечатка)
 *   - понижен
 *   - установлен/продлён/снят статус «под наблюдением» — CreditWatch,
 *     своя терминология АКРА (не "на пересмотре" НКР, не структурированная
 *     колонка НРА, не глаголы Эксперт РА)
 *
 * === НЕ ПРОВЕРЕНО ВЖИВУЮ (добавлено по аналогии, требует подтверждения) ===
 *   - "повышен" — по симметрии с "понижен", живого примера не было
 *   - "отозван" — по симметрии с остальными тремя агентствами
 *   - "пересмотрен" — встретился ОДИН раз, только в хвосте "также
 *     пересмотрен рейтинг выпусков..." без указания направления/грейда —
 *     здесь намеренно не пытаемся угадать новое значение, вся фраза после
 *     "также" просто остаётся в исходном тексте (source_title), не
 *     разбирается на структурированные поля
 *
 * === Прочие особенности ===
 *   - «cтабильный» — во ВСЕХ примерах первая буква ЛАТИНСКАЯ "c", не
 *     кириллическая "с". Похоже на системную опечатку в шаблоне рассылки
 *     АКРА, не разовый случай — нормализуем явно (fixCyrillicLookalikes()),
 *     иначе mapOutlook() не узнает слово.
 *   - Рейтинг иногда без "(RU)" вообще (например "BB-" у иностранного
 *     эмитента) — международная шкала, храним как есть строкой.
 *   - "также <текст>" (составное действие — тот же эмитент, доп. действие
 *     над рейтингом его же выпуска/выпусков) — НЕ разбирается на отдельную
 *     запись: нет отдельного ISIN/грейда в большинстве случаев, только
 *     констатация факта. Вся строка целиком уходит в source_title.
 */
final class AcraEmailParser
{
    /** Глаголы, меняющие грейд — порядок важен только для отчётности, не для матчинга. */
    private const GRADE_VERBS = ['подтверждён', 'присвоен', 'понижен', 'повышен', 'отозван', 'пересмотрен'];

    /** @var array<string, int> полное русское название месяца (родительный падеж, нижний регистр) => номер */
    private const MONTHS_GENITIVE = [
        'января' => 1, 'февраля' => 2, 'марта' => 3, 'апреля' => 4,
        'мая' => 5, 'июня' => 6, 'июля' => 7, 'августа' => 8,
        'сентября' => 9, 'октября' => 10, 'ноября' => 11, 'декабря' => 12,
    ];

    /**
     * Заголовок даты в письме — "03 сентября 2026 года" (полное название
     * месяца в родительном падеже + слово "года"), НЕ формат АКРА для
     * current_ratings ("28 авг 2026", см. RatingsNormalizer::
     * parseRussianMonthDate()) — другой формат, отдельный метод.
     */
    public static function parseDateHeader(string $raw): ?string
    {
        $raw = mb_strtolower(trim($raw));
        if (!preg_match('/^(\d{1,2})\s+([а-яё]+)\s+(\d{4})\s+года$/u', $raw, $m)) {
            return null;
        }

        $month = self::MONTHS_GENITIVE[$m[2]] ?? null;
        if ($month === null || !checkdate($month, (int) $m[1], (int) $m[3])) {
            return null;
        }

        return sprintf('%04d-%02d-%02d', (int) $m[3], $month, (int) $m[1]);
    }

    /**
     * Разбирает одну строку действия ("<подлежащее> — <действие>").
     * Возвращает null, если строка не похожа на рейтинговое действие
     * вообще (ни одного известного глагола/статуса не нашлось) — вызывающий
     * код должен залогировать это как "пропущено", не как ошибку: в письме
     * могут быть посторонние строки (приветствие, подпись).
     *
     * @return array{
     *   subject: string,
     *   isin: ?string,
     *   names: array<int, string>,
     *   verb: ?string,
     *   ratingTo: ?string,
     *   isExpected: bool,
     *   outlookTo: ?string,
     *   raw: string,
     * }|null
     */
    public static function parseActionLine(string $line): ?array
    {
        $line = trim($line);
        $parts = preg_split('/\s+—\s+/u', $line, 2);
        if ($parts === false || count($parts) !== 2) {
            return null;
        }
        [$subject, $action] = $parts;

        // "также <...>" — составное действие над тем же эмитентом (обычно
        // над рейтингом его же выпуска), см. докблок класса. Разбираем на
        // структурированные поля ТОЛЬКО текст ДО "также" — иначе глагол
        // или прогноз из хвоста мог бы случайно перебить основное действие
        // (например, если бы там встретился глагол, стоящий раньше в
        // GRADE_VERBS). Весь $line целиком всё равно уходит в source_title
        // у вызывающего кода — хвост не теряется, просто не парсится.
        $primary = preg_split('/\bтакже\b/ui', $action, 2)[0];

        $verb = self::detectGradeVerb($primary);
        $watch = self::detectWatchStatus($primary);
        if ($verb === null && $watch === null) {
            return null;
        }

        $isin = null;
        if (preg_match('/\(([A-Z]{2}[A-Z0-9]{9}\d)\)/', $subject, $m)) {
            $isin = $m[1];
        }

        $baseOutlook = null;
        if (preg_match('/прогноз\s*«([^»]+)»/ui', $primary, $m)) {
            $baseOutlook = RatingsNormalizer::mapOutlook(self::fixCyrillicLookalikes($m[1]));
        }

        $outlookTo = match ($watch) {
            'set' => 'under_review',
            'concluded' => $baseOutlook ?? 'review_concluded',
            default => $baseOutlook,
        };

        return [
            'subject' => $subject,
            'isin' => $isin,
            // Регионы/банки без кавычек — extractQuotedNames() вернёт []
            // (см. докблок класса), не ошибка, а известное ограничение.
            'names' => RatingsNormalizer::extractQuotedNames($subject),
            'verb' => $verb,
            'ratingTo' => self::extractGrade($primary, $verb),
            'isExpected' => (bool) preg_match('/ожидаем\w+\s+рейтинг/ui', $primary),
            'outlookTo' => $outlookTo,
            'raw' => $line,
        ];
    }

    private static function detectGradeVerb(string $action): ?string
    {
        foreach (self::GRADE_VERBS as $verb) {
            if (preg_match('/\b' . $verb . '\w*\b/ui', $action)) {
                return $verb;
            }
        }

        return null;
    }

    /** @return 'set'|'concluded'|null */
    private static function detectWatchStatus(string $action): ?string
    {
        if (preg_match('/снят[аы]?\s+статус\s*«?под\s+наблюдением»?/ui', $action)) {
            return 'concluded';
        }
        if (preg_match('/(установлен[а]?|продлён|продлена)\s+статус\s*«?под\s+наблюдением»?/ui', $action)) {
            return 'set';
        }

        return null;
    }

    /**
     * "AAA(RU)", "eAAA(RU)" (ожидаемый рейтинг, префикс "e" — не отдельная
     * буква шкалы), "BB-" (международная шкала, без "(RU)"), "A+(RU)".
     * Для "отозван" — грейд не указывается, литерал "отозван" (тот же
     * приём, что и у Эксперт РА/НКР для отзыва рейтинга).
     */
    private static function extractGrade(string $action, ?string $verb): ?string
    {
        if ($verb === 'отозван') {
            return 'отозван';
        }

        if (preg_match('/(?:на\s+уровне|до\s+уровня)\s+(e?[A-Z]{1,4}[+\-]?(?:\(RU\))?)/u', $action, $m)) {
            return $m[1];
        }

        return null;
    }

    /**
     * Во ВСЕХ проверенных примерах слово "стабильный" в письмах АКРА
     * начинается с латинской "c", не кириллической "с" — похоже на
     * артефакт их шаблона рассылки. Заменяем только классические
     * похожие буквы (латиница → кириллица), достаточно для короткого
     * слова прогноза — не трогаем произвольный текст целиком.
     */
    private static function fixCyrillicLookalikes(string $text): string
    {
        static $map = [
            'c' => 'с', 'C' => 'С', 'e' => 'е', 'E' => 'Е', 'o' => 'о', 'O' => 'О',
            'p' => 'р', 'P' => 'Р', 'a' => 'а', 'A' => 'А', 'x' => 'х', 'X' => 'Х',
            'y' => 'у', 'Y' => 'У', 'H' => 'Н', 'K' => 'К', 'M' => 'М', 'T' => 'Т', 'B' => 'В',
        ];

        return strtr($text, $map);
    }
}
