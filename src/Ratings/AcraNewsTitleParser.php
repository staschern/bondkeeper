<?php

declare(strict_types=1);

namespace BondKeeper\Ratings;

/**
 * ШАБЛОН/РАЗВЕДКА, сентябрь 2026 — чистый (без БД/сети) разбор ЗАГОЛОВКОВ
 * пресс-релизов АКРА С САЙТА (acra-ratings.ru/press-releases/), НЕ из
 * email-рассылки (для писем — см. AcraEmailParser, другая грамматика:
 * "<Подлежащее> — <действие>" пассивным залогом, тогда как здесь активный
 * залог "АКРА <глагол> ...", по образцу заголовков НКР).
 *
 * Проверено на 10 реальных заголовках списка + 1 полной детальной странице
 * (сохранённые вживую страницы сайта, присланные пользователем — не
 * автоматический опрос, сайт блокирует автоматические запросы, см.
 * docs/STAGE3_RATINGS.md). Структура источников:
 *   - список ("https://www.acra-ratings.ru/press-releases/"): карточки
 *     `.documents-row.search-table-row`, ссылка `a.item__title[href]`,
 *     дата `.documents-row__item[data-type="date"]` в формате
 *     "4 сен 2026" (тот же формат, что и у AcraImporter — см.
 *     RatingsNormalizer::parseRussianMonthDate()).
 *   - деталь (например ".../press-releases/7241/"): дата публикации в
 *     `<time class="publication_date" datetime="04.09.2026 10:21:08">`,
 *     ИНН — в таблице "Регуляторное раскрытие", строка "Идентификационный
 *     номер налогоплательщика рейтингуемого лица" → соседняя ячейка
 *     "ИНН: 9714067913" (без скобок "(ИНН)", в отличие от формулировки
 *     НКР — общий с НКР regex сюда не подойдёт буквально, тот же урок,
 *     что уже был у Эксперт РА).
 *
 * === Реальный найденный баг: кириллица вместо латиницы в грейдах, ВПЕРЕМЕШКУ ===
 *
 * На 10 реальных заголовках грейд писался то латиницей, то кириллицей —
 * ДАЖЕ ВНУТРИ ОДНОГО И ТОГО ЖЕ ТОКЕНА: "AАA(RU)" (Latin A + Cyrillic А +
 * Latin A — все три визуально одинаковы), "еA(RU)" (Cyrillic е —
 * префикс "ожидаемый" — + Latin A), "ВВ(RU)" (обе буквы кириллические).
 * Непоследовательно от релиза к релизу — похоже на то, что тексты
 * пресс-релизов набирают вручную разные сотрудники АКРА, переключая
 * раскладку клавиатуры не всегда одинаково, а не на единый системный баг
 * одного шаблона (как "cтабильный" с латинской "c" в email-рассылке —
 * см. AcraEmailParser). Раздельное определение "какая буква тут должна
 * быть" ненадёжно — вместо этого: ищем ВСЕ похожие на грейд подстроки
 * (латиница ИЛИ кириллица вперемешку), нормализуем каждую (заменяем
 * визуально совпадающие кириллические буквы на латинские), и оставляем
 * только те, что ПОСЛЕ нормализации точно совпадают с одной из реальных
 * форм грейда (AAA/AA/A/BBB/BB/B/CCC/CC/C/D/SD, опционально с "+"/"-",
 * опционально с префиксом "e" и суффиксом "(RU)"). Это заодно бесплатно
 * отсеивает кириллические аббревиатуры вроде "ПАО"/"АО"/"ООО"/"КБ",
 * которые тоже 1-4 буквы в верхнем регистре, но не сводятся ни к одной
 * настоящей форме грейда после нормализации (проверено: "ПАО" → "ПAО",
 * не входит в список; "АО" → "AO", тоже не входит).
 *
 * Скобки с ISIN (например "(RU000A103N84)") перед сканированием
 * вырезаются отдельно — иначе часть подстрок внутри ISIN теоретически
 * могла бы случайно пройти проверку формы (не встретилось ни разу на
 * 10 примерах, но исключить дешевле, чем полагаться на везение).
 *
 * === Глаголы: подтверждены вживую "присвоило"/"отозвало"/"понизило" ===
 *
 * "подтвердило"/"повысило" добавлены по аналогии (симметрично с уже
 * встретившимися глаголами и с уже проверенным AcraEmailParser, где та
 * же пара глаголов есть в пассивном залоге) — не встретились в 10
 * заголовках списка, требуют подтверждения при появлении вживую.
 * "изменило" — совсем гипотетический (по аналогии с НКР), ни разу не
 * встречался ни в одном источнике АКРА (ни на сайте, ни в письмах).
 *
 * === Статус "под наблюдением" — своя фраза, не как в current_ratings ===
 *
 * Реальный пример: "АКРА ПРИСВОИЛО СТАТУС «ПОД НАБЛЮДЕНИЕМ» КРЕДИТНОМУ
 * РЕЙТИНГУ ООО «АЛЬФА-ЛИЗИНГ» АА-(RU), ПРОГНОЗ «ПОЗИТИВНЫЙ»..." — тот
 * же эмитент и то же событие, что уже найдено вживую для current_ratings
 * (AcraImporter::combineOutlookWithAcraWatchSuffix() — там формат
 * "Позитивный, под наблюдением" в выгрузке). В новостном заголовке
 * фраза другая: "СТАТУС «ПОД НАБЛЮДЕНИЕМ»" рядом с обычным глаголом
 * (здесь — "присвоило", не отдельный глагол вроде "установило"/
 * "продлило" у НКР/Эксперт РА). detectWatchPhrase() ищет её отдельно от
 * глагола действия; extractOutlook() комбинирует направление прогноза
 * со статусом наблюдения через RatingsNormalizer::combineWithWatchStatus()
 * — тот же метод, что уже проверен для НРА/AcraImporter, просто с другим
 * источником признака "под наблюдением".
 *
 * === Известное ограничение: вложенные кавычки в имени компании ===
 *
 * Один реальный заголовок: "...ПАО «АФК «СИСТЕМА» ДО УРОВНЯ..." — сайт
 * АКРА сам не закрыл первую кавычку перед "СИСТЕМА", из-за чего
 * извлечённое имя — "АФК «СИСТЕМА" (с незакрытой кавычкой внутри), не
 * чистое "АФК Система". Единичный случай на 10 примеров, не системная
 * закономерность — не пытаемся угадывать общее правило по одному
 * примеру; IssuerMatcher::findIssuerIdByName() всё равно не найдёт
 * точного совпадения с таким "грязным" именем, компания уйдёт в "не
 * сопоставлено" (не в ошибку) — известное, не полностью решённое
 * ограничение, как и у Эксперт РА с регионами.
 */
final class AcraNewsTitleParser
{
    private const VERBS = ['присвоило', 'подтвердило', 'повысило', 'понизило', 'отозвало', 'изменило'];

    /** Реальные формы грейда АКРА (без учёта регистра/скобок/e-префикса — см. isValidGradeShape()). */
    private const GRADE_WORDS = ['AAA', 'AA', 'A', 'BBB', 'BB', 'B', 'CCC', 'CC', 'C', 'D', 'SD'];

    public static function matchVerb(string $title): ?string
    {
        if (!preg_match('/^АКРА\s+(' . implode('|', self::VERBS) . ')\s/ui', $title, $m)) {
            return null;
        }

        return mb_strtolower($m[1]);
    }

    public static function isCreditRatingAction(string $title): bool
    {
        return (bool) preg_match('/кредитн\w+\s+рейтинг/ui', $title);
    }

    /** "СТАТУС «ПОД НАБЛЮДЕНИЕМ»"/"«СНЯТ СО СТАТУСА «ПОД НАБЛЮДЕНИЕМ»" — см. докблок класса. */
    public static function detectWatchPhrase(string $title): bool
    {
        return (bool) preg_match('/статус\s*«?под\s+наблюдением»?/ui', $title);
    }

    /**
     * "отозвало" — литерал 'отозван' (тот же приём, что у НКР/Эксперт РА).
     * Иначе — сканирует title на все похожие на грейд подстроки (см.
     * докблок класса про смешение кириллицы/латиницы), берёт ПЕРВУЮ,
     * которая после нормализации точно совпадает с реальной формой
     * грейда — этого достаточно на всех 10 проверенных заголовках
     * независимо от того, предшествует ли грейду "на уровне"/"до
     * уровня" или он идёт сразу после "рейтинг"/после имени в кавычках
     * (АКРА непоследователен в самой формулировке, не только в буквах).
     */
    public static function extractGrade(string $title, string $verb): ?string
    {
        if ($verb === 'отозвало') {
            return 'отозван';
        }

        // ISIN в скобках может теоретически содержать подряд идущие
        // буквы, случайно похожие на форму грейда после нормализации —
        // не встретилось на практике, но дешевле вырезать заранее, чем
        // полагаться на то, что не встретится и впредь.
        $withoutIsin = preg_replace('/\([A-Z0-9]{6,}\)/u', ' ', $title) ?? $title;

        // Без завершающего \b: после опциональной группы "(RU)" следующий
        // символ обычно "," или конец строки — оба НЕ образуют границу
        // слова после закрывающей ")" (обе стороны не-словесные), из-за
        // чего \b на конце заставлял бы движок откатиться и отбросить
        // уже найденный "(RU)" (проверено вживую на реальных заголовках —
        // без этой правки "AAA(RU)" находился только как "AAA").
        // [eе]? — не только латинская "e" префикса "ожидаемый", но и её
        // кириллический двойник "е" (U+0435) — реальный найденный случай
        // ("еA(RU)"): движок regex вообще не захватит букву в капчер, если
        // класс символов её не перечисляет, до normalizeGradeLookalikes()
        // очередь не доходит вовсе.
        preg_match_all('/\b[eе]?[A-ZА-Я]{1,4}[+\-]?(?:\s*\(RU\))?/u', $withoutIsin, $m);
        foreach ($m[0] as $candidate) {
            $normalized = self::normalizeGradeLookalikes(trim($candidate));
            if (self::isValidGradeShape($normalized)) {
                return $normalized;
            }
        }

        return null;
    }

    /**
     * Направление прогноза из "ПРОГНОЗ «...»"/"ПРОГНОЗ НА «...»" (второй
     * вариант — реальный найденный случай: "ИЗМЕНИВ ПРОГНОЗ НА
     * «РАЗВИВАЮЩИЙСЯ»", простой `прогноз\s*«` его не поймал бы). Статус
     * "под наблюдением" (см. detectWatchPhrase()) комбинируется с базовым
     * направлением тем же методом, что уже проверен для НРА/AcraImporter
     * (RatingsNormalizer::combineWithWatchStatus()) — тем самым один и
     * тот же результат (например under_review_positive) получается что
     * из выгрузки current_ratings ("Позитивный, под наблюдением"), что
     * из этого заголовка ("СТАТУС «ПОД НАБЛЮДЕНИЕМ» ... ПРОГНОЗ
     * «ПОЗИТИВНЫЙ»"), хотя формулировки разные.
     */
    public static function extractOutlook(string $title): ?string
    {
        $base = null;
        if (preg_match('/прогноз[^«»]{0,10}«([^»]+)»/ui', $title, $m)) {
            $base = RatingsNormalizer::mapOutlook($m[1]);
        }

        return self::detectWatchPhrase($title)
            ? RatingsNormalizer::combineWithWatchStatus($base, 'под наблюдением')
            : $base;
    }

    /**
     * Кандидаты на название эмитента — все названия в кавычках (см.
     * RatingsNormalizer::extractQuotedNames(), общий метод для НКР/
     * Эксперт РА — уже отсекает цитаты вида "«рейтинг на пересмотре...»"/
     * "«под наблюдением»" по словам "рейтинг/прогноз/пересмотр/
     * наблюдени" внутри кавычек, проверено, что этого достаточно и для
     * реальной фразы АКРА "«ПОД НАБЛЮДЕНИЕМ»"). У АКРА нашёлся СВОЙ
     * дополнительный ложноположительный случай: голое слово прогноза без
     * какого-либо из этих ключевых слов рядом ("ПРОГНОЗ «СТАБИЛЬНЫЙ»" —
     * общий фильтр это не ловит, реально проверено на живом заголовке).
     * Дополнительно отсекаем кандидатов, которые ЦЕЛИКОМ сводятся к
     * одному из 4 слов прогноза (RatingsNormalizer::mapOutlookFromProse()).
     *
     * @return array<int, string>
     */
    public static function extractQuotedNames(string $title): array
    {
        return array_values(array_filter(
            RatingsNormalizer::extractQuotedNames($title),
            static fn (string $name): bool => RatingsNormalizer::mapOutlookFromProse($name) === null,
        ));
    }

    /**
     * ISIN конкретного выпуска облигаций прямо в скобках в заголовке —
     * реальные примеры: "...ВЫПУСКА ОБЛИГАЦИЙ АО «РОССЕЛЬХОЗБАНК»
     * (RU000A103N84) В СВЯЗИ С ПОГАШЕНИЕМ...", "...ОБЛИГАЦИЙ РОСТОВСКОЙ
     * ОБЛАСТИ (RU000A10FZZ1) КРЕДИТНЫЙ РЕЙТИНГ...". Второй пример —
     * именно тот случай, ради которого это нужно: у региона нет ни ИНН
     * (см. AcraNewsImporter — на детальной странице поле "Идентификационный
     * номер..." для муниципальных облигаций пусто), ни названия в
     * кавычках (RatingsNormalizer::extractQuotedNames() тут вернёт []) —
     * ISIN остаётся ЕДИНСТВЕННЫМ способом сопоставить такую строку с
     * securities.isin (см. IssuerMatcher::findIssuerIdByIsin()).
     */
    public static function extractIsin(string $title): ?string
    {
        if (preg_match('/\(([A-Z]{2}[A-Z0-9]{9}\d)\)/', $title, $m)) {
            return $m[1];
        }

        return null;
    }

    private static function isValidGradeShape(string $normalized): bool
    {
        return (bool) preg_match('/^e?(?:' . implode('|', self::GRADE_WORDS) . ')[+\-]?(?:\(RU\))?$/', $normalized);
    }

    private static function normalizeGradeLookalikes(string $grade): string
    {
        static $map = ['А' => 'A', 'В' => 'B', 'С' => 'C', 'Е' => 'E', 'е' => 'e'];

        return strtr($grade, $map);
    }
}
