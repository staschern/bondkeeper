    }

    /**
     * Новость про ОЖИДАЕМЫЙ рейтинг (выпуска, который ещё не размещён) —
     * по словам "ожидаемый … рейтинг" в любом падеже/регистре (НКР
     * "ожидаемый кредитный рейтинг eAA.ru", Эксперт РА "присвоил ожидаемый
     * кредитный рейтинг облигациям …", АКРА "ОЖИДАЕМЫЙ КРЕДИТНЫЙ РЕЙТИНГ")
     * или по пометке "(EXP)".
     */
    public static function isExpectedRatingTitle(string $title): bool
    {
        $lower = mb_strtolower($title);

        return (bool) preg_match('/ожидаем[а-яё]*\s+(?:кредитн[а-яё]*\s+)?рейтинг|\(exp\)/u', $lower);
    }

    /**
     * Рейтинг латиницей: агентства иногда набирают буквы рейтинга
     * кириллическими двойниками — у Эксперт РА в 177 новостях из 946
     * ("ruВВВ+", "ruАA-"), у НКР "eAАА.ru", у АКРА "еA(RU)" (28.09.2026).
     * На вид одинаково, но для базы "ruАА" и "ruAA" — разные строки: сверка
     * показывает расхождение там, где его нет, сравнение рейтингов ошибается.
     * Заменяем А, В, С, Е и е (префикс ожидаемого рейтинга) на латиницу.
     * Слово "отозван" и любой другой текст с кириллицей в нижнем регистре
     * (кроме одиночной "е") не трогаем — это не рейтинг.
     */
    public static function normalizeGrade(string $grade): string
    {
        if (preg_match('/[а-дж-яё]/u', $grade)) {
            return $grade;
        }

        return strtr($grade, ['А' => 'A', 'В' => 'B', 'С' => 'C', 'Е' => 'E', 'е' => 'e']);
    }

    /**
     * Новость про рейтинг СУБОРДИНИРОВАННЫХ облигаций — не влияет на
     * рейтинг компании при любом действии (решение пользователя,
     * 28.09.2026): у субордов рейтинг обычно ниже рейтинга банка (Банк ГПБ:
     * ruAAA у банка, ruAA- у субординированных), и раньше такая новость
     * перезаписывала рейтинг банка. За июнь–сентябрь 2026 у Эксперт РА 7
     * таких новостей (ТБанк, Альфа-Банк, Банк ГПБ, ПСБ), у НКР — ни одной.
     * "Несубординированные" (обычные) облигации не задеваются — слово
     * должно начинаться именно с "субординированн". Совмещённая новость
     * "рейтинги ПАО «Х» и его субординированных облигаций" — это новость
     * про компанию (isBondIssueRatingTitle() = false), она пишется.
     *
     * Второй признак — "T2" в коде серии (решение пользователя,
     * 29.09.2026): T2 — субординированный капитал второго уровня. Альфа-Банк
     * дважды не написал слова: "присвоил кредитный рейтинг облигациям АО
     * «АЛЬФА-БАНК» серии T2-CR-10 на уровне ruA+" (27.03.2026, и T2-CR-06
     * 24.03.2026), хотя серию T2-CR-07 тот же Эксперт РА называет
     * субординированной. Остальные живые коды — "001SUB-T2-01" (ТБанк),
     * "ГПБ-Т2-03Д" (Банк ГПБ), T латиницей или кириллицей. Только в коде
     * серии (после "серии"/"серий", в начале кода или после дефиса): "Т1" —
     * название компании у НКР (ООО «Т1»), его не трогаем. На ленте
     * Эксперт РА (946 новостей) признак добавляет ровно эти два заголовка,
     * в 1069 заголовках НКР — ни одного.
     */
    public static function isSubordinatedBondRating(string $text): bool
    {
        if (!self::isBondIssueRatingTitle($text)) {
            return false;
        }
        $lower = mb_strtolower($text);

        return (bool) preg_match('/(?<![а-яё])субординированн[а-яё]*\s+(?:бессрочн[а-яё]*\s+)?облигаци/u', $lower)
            || (bool) preg_match('/(?<![а-яё])сери[а-яё]*\s+(?:[^\s,]*-)?[tт]2-/u', $lower);
    }

    /**
     * "D"/"SD" (дефолт/выборочный дефолт) — по прямому запросу
     * пользователя (найдено вживую: НКР понизило ООО «ЛКХ» до "D", в
     * заголовке про прогноз ничего не было, и в current_ratings прогноз
     * молча остался старым от прошлого действия): для дефолтного грейда
     * прогноз не предусмотрен вообще — CurrentRatingsSync::sync()
     * вызывает этот метод и, если true, пишет outlook = NULL независимо
     * от того, что было в кэше или в самом действии.
     *
     * Буквенный код "D"/"SD" — общий для всех агентств проекта (см.
     * NkrTitleParser::extractRatingChange() и
     * AcraNewsTitleParser::GRADE_WORDS, где оба подтверждены вживую),
     * но каждое агентство украшает его по-своему: НКР — голым словом без
     * декораций, АКРА — опциональным ведущим "e"/"е" (грейд "ожидаемый")
     * и/или хвостовым "(RU)", Эксперт РА — ведущим "ru" (весь их алфавит
     * с этим префиксом, не только D), НРА — хвостовым "|ru|" (см. реальный
     * пример "AA|ru|" в STAGE3_RATINGS.md). Для Эксперт РА/НРА само "D"
     * вживую не встречалось (только по аналогии с общей схемой
     * декораций их шкалы) — снимаем декорации и сравниваем именно
     * буквенный код, а не гадаем про регистр/скобки по каждому агентству
     * отдельно.
     */
    public static function isDefaultGrade(?string $rating): bool
    {
        if ($rating === null) {
            return false;
        }

        $normalized = mb_strtoupper(trim($rating));
        $normalized = preg_replace('/^E/u', '', $normalized) ?? $normalized;
        $normalized = preg_replace('/^RU/u', '', $normalized) ?? $normalized;
        $normalized = preg_replace('/\s*\(RU\)$/u', '', $normalized) ?? $normalized;
        $normalized = preg_replace('/\.RU$/u', '', $normalized) ?? $normalized;
        $normalized = preg_replace('/\|RU\|$/u', '', $normalized) ?? $normalized;

        return in_array(trim($normalized), ['D', 'SD'], true);
    }
