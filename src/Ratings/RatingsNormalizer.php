<?php

declare(strict_types=1);

namespace BondKeeper\Ratings;

/**
 * Общие для НРА/НКР (и, вероятно, будущих агентств) преобразования сырых
 * текстовых значений из выгрузок в формат схемы БД. Вынесено в отдельный
 * класс, а не продублировано в каждом импортёре — вокабуляр прогноза на
 * русском совпадает у обоих агентств, дата в обоих выгрузках — DD.MM.YYYY.
 */
final class RatingsNormalizer
{
    /**
     * current_ratings.outlook — ENUM('positive','stable','negative','developing',
     * 'under_review'/'under_review_negative'/'under_review_positive'/
     * 'under_review_stable'/'under_review_developing'/'review_concluded',
     * см. миграцию 017; 'indefinite' — миграция 026). Этот метод — только
     * "базовые" направления;
     * статус "на пересмотре"/"под наблюдением" собирается ОТДЕЛЬНО (см.
     * combineWithWatchStatus() для НРА, extractReviewStatusFromProse() для
     * НКР) — не здесь, чтобы не разрастить один exact-match на десяток
     * составных случаев. Для всего, что не сводится однозначно к одному
     * из 4 базовых значений, — честно NULL, а не приблизительная догадка.
     */
    public static function mapOutlook(string $raw): ?string
    {
        return match (mb_strtolower(trim($raw))) {
            'стабильный' => 'stable',
            'позитивный' => 'positive',
            'негативный' => 'negative',
            // "Неопределённый" (НКР) и "развивающийся" (Эксперт РА, АКРА,
            // НРА) — разные понятия (решение пользователя, сентябрь 2026,
            // миграция 026): у НКР — высокая вероятность ИЗМЕНЕНИЯ
            // рейтинга с неизвестным направлением; у остальных —
            // равновероятны несколько исходов, включая сохранение.
            'неопределенный', 'неопределённый' => 'indefinite',
            'развивающийся' => 'developing',
            default => null,
        };
    }

    /**
     * НРА иногда (не всегда — см. combineWithWatchStatus()) дублирует
     * статус наблюдения прямо в тексте колонки "Прогноз": "Стабильный -
     * под наблюдением", "Без прогноза - снято с наблюдения". Отрезаем
     * этот суффикс, чтобы БАЗОВОЕ направление (до дефиса) всё равно
     * прошло через обычный mapOutlook() — статус наблюдения учитывается
     * отдельно, по колонке "Под наблюдением" (надёжнее свободного текста).
     */
    public static function stripWatchSuffix(string $raw): string
    {
        return trim(preg_replace('/\s*-\s*(под наблюдением|снято с наблюдения)\s*$/ui', '', $raw) ?? $raw);
    }

    /**
     * НРА даёт статус "на пересмотре" СТРУКТУРИРОВАННО — отдельной
     * колонкой "Под наблюдением" (значения: "", "Под наблюдением", "Снято
     * с наблюдения"; проверено на живой выгрузке — 130/209/602 строк
     * соответственно), а не свободным текстом, как НКР. Это надёжнее:
     * не нужно парсить формулировки — просто три известных значения.
     *
     * $baseOutlook — результат mapOutlook(stripWatchSuffix($raw['Прогноз']))
     * — базовое направление ДО учёта статуса наблюдения.
     *
     * Правила (решение пользователя, сентябрь 2026, на реальных данных —
     * ни разу не встретилось "Позитивный"/"Негативный" в сочетании с
     * "под наблюдением" в колонке "Прогноз" НРА, поэтому under_review_
     * positive/negative для НРА пока чисто гипотетические, но обработаны
     * той же веткой на случай, если встретятся):
     *   - "Под наблюдением" + база → under_review[_negative|_positive|
     *     _stable|_developing], без базы → under_review (голое).
     *   - "Снято с наблюдения" + база есть → сама база (наблюдение снято,
     *     это уже обычный прогноз); базы нет (только этот случай
     *     реально встретился — "Без прогноза - снято с наблюдения") →
     *     review_concluded — пользователь явно попросил отдельное
     *     значение, не молчаливый NULL: сам факт "снято этим действием"
     *     значим, даже когда текущий прогноз не назван.
     *   - "" (не под наблюдением вообще) → база как есть, без изменений.
     * Сама логика — общее правило combineWithWatch() (одно для всех
     * агентств); для обеих колонок НРА сразу — outlookFromNraColumns().
     */
    public static function combineWithWatchStatus(?string $baseOutlook, string $watchColumnRaw): ?string
    {
        return self::combineWithWatch($baseOutlook, match (mb_strtolower(trim($watchColumnRaw))) {
            'под наблюдением' => self::WATCH_ON,
            'снято с наблюдения' => self::WATCH_OFF,
            default => null,
        });
    }

    /**
     * НКР статус "на пересмотре" (то же, что "под наблюдением" у НРА и
     * Эксперт РА) даёт только свободным текстом. У НКР ровно три
     * формулировки (проверено по 1069 заголовкам, сентябрь 2026):
     * "с возможностью понижения" → under_review_negative, "с возможностью
     * повышения" → under_review_positive, "— неопределённый прогноз" →
     * under_review_indefinite (миграция 026: статус пересмотра + направление
     * «неопределённый», по той же схеме, что under_review_developing у НРА).
     * Голое under_review — только если направление не названо вовсе.
     * Проверяется ДО обычного mapOutlookFromProse() — это отдельный,
     * более специфичный статус.
     */
    public static function extractReviewStatusFromProse(string $text): ?string
    {
        $text = mb_strtolower($text);
        if (!preg_match('/на пересмотре|под наблюдением/u', $text)) {
            return null;
        }

        return match (true) {
            (bool) preg_match('/возможностью понижения|возможностью снижения/u', $text) => 'under_review_negative',
            (bool) preg_match('/возможностью повышения/u', $text) => 'under_review_positive',
            (bool) preg_match('/неопределённ|неопределенн/u', $text) => 'under_review_indefinite',
            default => 'under_review',
        };
    }

    /** Статус наблюдения, названный в тексте действия: поставлен/продлён/сохранён. */
    public const WATCH_ON = 'on';
    /** Статус наблюдения снят. */
    public const WATCH_OFF = 'off';

    /**
     * ОБЩЕЕ правило чтения статуса "под наблюдением" из текста действия —
     * для всех агентств (решение пользователя, 28.09.2026: "по
     * возможности универсально во всех импортёрах"). Раньше у НРА,
     * Эксперт РА, выгрузки АКРА, новостей АКРА и писем АКРА было по своему
     * разбору, и они расходились: новости АКРА читали "…И СНЯЛО СТАТУС «ПОД
     * НАБЛЮДЕНИЕМ»" как "поставлен" (проверяли только упоминание), письмо
     * АКРА и Эксперт РА теряли прогноз при "продлил статус".
     *
     * WATCH_OFF — снят: "снял/сняло/сняв/снят (со) статус(а) «под
     * наблюдением»", "статус «под наблюдением» снят" (и "cнял" с латинской c
     * — реальная опечатка Эксперт РА). WATCH_ON — установлен/присвоен/продлён/
     * сохранён в любой форме ("присвоило статус", "продлен статус", "по
     * рейтингу установлен статус", "статус «под наблюдением» продлён"), а
     * также упоминание статуса без глагола (как раньше у новостей АКРА).
     * Предложения "Ранее …" (прежнее состояние) не учитываются. NULL — о
     * статусе ничего не сказано.
     *
     * НКР говорит "на пересмотре" с направлением внутри формулировки — у
     * неё свой разбор, extractReviewStatusFromProse().
     */
    public static function watchStatusFromText(string $text): ?string
    {
        $text = mb_strtolower($text);
        $text = preg_replace('/(?:^|(?<=[.!?]\s))ранее[^.]*\./u', ' ', $text) ?? $text;

        $status = 'статус\w*\s*«?\s*под\s*«?\s*наблюдени\w*»?';
        $off = '[сc]нял\w*|[сc]нят[аоы]?|[сc]няв|[сc]нимает';
        $on = 'установил\w*|установлен\w*|установив|присвоил\w*|присвоен\w*|присвоив|продлил\w*|продлен\w*|продлён\w*|продлив|сохранил\w*|сохранен\w*|сохранён\w*|сохранив';

        if (preg_match("/(?:{$off})\s+(?:со\s+)?{$status}|{$status}\s+(?:{$off})/u", $text)) {
            return self::WATCH_OFF;
        }
        if (preg_match("/(?:{$on})\s+{$status}|{$status}\s+(?:{$on})|{$status}/u", $text)) {
            return self::WATCH_ON;
        }

        return null;
    }

    /**
     * ОБЩЕЕ правило сложения статуса наблюдения с прогнозом — для всех
     * агентств (решение пользователя, 28.09.2026): если агентство
     * поставило/продлило наблюдение и прямо называет прогноз, сохраняются
     * ОБА факта — under_review_<прогноз> (реальные случаи: НРА «Оил Ресурс»
     * — "рейтинг продолжает действовать …, прогноз «стабильный»"; Эксперт РА
     * — "продлил статус «под наблюдением» … Рейтинг компании продолжает
     * действовать на уровне ruAA- со стабильным прогнозом").
     *   - WATCH_ON: under_review_<прогноз>; прогноза нет (облигации, CC/C) —
     *     under_review.
     *   - WATCH_OFF: сам прогноз; прогноза нет — review_concluded.
     *   - NULL: прогноз как есть.
     */
    public static function combineWithWatch(?string $baseOutlook, ?string $watch): ?string
    {
        if ($watch === self::WATCH_ON && $baseOutlook !== null && str_starts_with($baseOutlook, 'under_review')) {
            return $baseOutlook;
        }

        return match ($watch) {
            self::WATCH_ON => match ($baseOutlook) {
                'negative' => 'under_review_negative',
                'positive' => 'under_review_positive',
                'stable' => 'under_review_stable',
                'developing' => 'under_review_developing',
                'indefinite' => 'under_review_indefinite',
                default => 'under_review',
            },
            self::WATCH_OFF => $baseOutlook ?? 'review_concluded',
            default => $baseOutlook,
        };
    }

    /**
     * Прогноз НРА из двух колонок выгрузки: "Прогноз" ("Стабильный",
     * "Развивающийся - под наблюдением", "Без прогноза - снято с
     * наблюдения", …) и "Под наблюдением" ("", "Под наблюдением", "Снято с
     * наблюдения"). Статус — из колонки "Под наблюдением", а если она
     * пустая — из окончания колонки "Прогноз" (реальный случай ПАО
     * «ЕвроТранс» 09.04.2026: "Без прогноза - под наблюдением" при пустой
     * колонке, в пресс-релизе — "продлив статус «под наблюдением»"; раньше
     * получался NULL). Одна функция для импортёра и сверки НРА.
     */
    public static function outlookFromNraColumns(string $prognozRaw, string $watchColumnRaw): ?string
    {
        $base = self::mapOutlook(self::stripWatchSuffix($prognozRaw));

        $watch = match (mb_strtolower(trim($watchColumnRaw))) {
            'под наблюдением' => self::WATCH_ON,
            'снято с наблюдения' => self::WATCH_OFF,
            default => null,
        };
        if ($watch === null) {
            if (preg_match('/-\s*под\s+наблюдением\s*$/ui', $prognozRaw)) {
                $watch = self::WATCH_ON;
            } elseif (preg_match('/-\s*снято\s+с\s+наблюдения\s*$/ui', $prognozRaw)) {
                $watch = self::WATCH_OFF;
            }
        }

        return self::combineWithWatch($base, $watch);
    }

    /**
     * Защитный барьер против нестандартных шкал (суффикс "sf" —
     * structured finance). Изначально написан для НКР (где вживую не
     * встретился ни разу), но подтвердился РЕАЛЬНО нужным для Эксперт РА
     * (сентябрь 2026, живая лента: "...на уровне ruAAA.sf" — 12 из 200
     * проверенных новостей) — Эксперт РА рейтингует структурированное
     * финансирование, и без этого барьера ".sf" отбрасывался бы молча
     * (общий регэксп грейда останавливается на точке и извлёк бы просто
     * "ruAAA", как будто это обычный корпоративный рейтинг). Вынесен сюда
     * из NkrTitleParser, когда понадобился второму агентству — общая,
     * не специфичная для НКР проверка.
     *
     * Проверка по целому слову ("\bsf\b"), не по подстроке — случайное
     * совпадение в русском тексте практически исключено.
     *
     * Ипотечные ценные бумаги (решение пользователя, 03.10.2026): любая
     * новость про них исключается целиком — это отдельный продукт, не
     * облигации компании ("не просто так там не написано про облигации").
     * Живой случай: "АКРА ОТОЗВАЛО КРЕДИТНЫЙ РЕЙТИНГ ВЫПУСКА ИПОТЕЧНЫХ
     * ЦЕННЫХ БУМАГ ООО «ДОМ.РФ ИПОТЕЧНЫЙ АГЕНТ» … В СВЯЗИ С ПОГАШЕНИЕМ
     * ВЫПУСКА" (30.09.2026) поставил компании "отозван". Только сами слова
     * "ипотечные ценные бумаги" в любом падеже — название компании
     * («Ипотечный агент») и другие формулировки не задеваются.
     */
    public static function isNonStandardRating(string $title): bool
    {
        return (bool) preg_match('/\bsf\b/ui', $title)
            || (bool) preg_match('/ипотечн[а-яё]*\s+ценн[а-яё]*\s+бумаг/u', mb_strtolower($title));
    }

    /**
     * Все названия в «ёлочках» из заголовка, без дублей, в порядке
     * появления. Общий метод для НКР и Эксперт РА — оба кладут в кавычки
     * названия юрлиц в заголовках пресс-релизов/новостей (номера серий
     * облигаций, даты и т.п. в кавычки не попадают).
     *
     * Два реальных найденных вживую случая, ломающих наивное допущение
     * "в кавычках — всегда название компании", оба закрыты одним и тем же
     * фильтром:
     *   - НКР: "...ООО «ЛКХ» с B.ru до CC.ru, прогноз — «рейтинг на
     *     пересмотре с возможностью понижения»" — вторая пара кавычек
     *     цитирует статус прогноза, не компанию;
     *   - Эксперт РА: "...и снял статус «под наблюдением»" — та же
     *     история, другая формулировка статуса.
     * Отсекаем такие кандидаты двумя эвристиками: 1) название юрлица
     * всегда начинается с заглавной буквы, цитата статуса — со строчной;
     * 2) дополнительно отсекаем кандидатов со словами
     * "рейтинг/прогноз/пересмотр/наблюдени" (в названии реальной компании
     * такие слова практически невозможны).
     *
     * Эксперт РА, в отличие от НКР, непоследователен в стиле кавычек —
     * часть названий в «ёлочках» (основной, регулярный стиль), но
     * заметная доля — в ПРЯМЫХ кавычках: `ООО "Сибэнергомаш - БКЗ"`,
     * `АО "АБЗ-1"`, `ПАО "РусГидро"` (проверено вживую, сентябрь 2026 —
     * без учёта прямых кавычек порядка 20% реальных новостей уходили в
     * "не сопоставлено", хотя компания есть в тексте). Оба стиля
     * собираются и объединяются здесь. Известное ограничение, не
     * решаемое кавычками вообще: часть названий (обычно регионы/
     * субъекты РФ — "Ульяновской области", "Республики Башкортостан" —
     * и один случай ALL CAPS без кавычек, "АО РОСЭКСИМБАНК") не берутся
     * в кавычки НИКАКОГО стиля — не резолвятся этим методом в принципе;
     * для BondKeeper (фокус на корпоративных облигациях, не суверенном/
     * субфедеральном долге) это, по всей видимости, не критично.
     *
     * @return array<int, string>
     */
    public static function extractQuotedNames(string $title): array
    {
        preg_match_all('/«([^»]+)»/u', $title, $m1);
        preg_match_all('/"([^"]+)"/u', $title, $m2);
        $names = array_values(array_unique(array_merge($m1[1], $m2[1])));

        return array_values(array_filter(
            $names,
            static fn (string $name): bool => preg_match('/^[A-ZА-ЯЁ]/u', $name) === 1
                && preg_match('/рейтинг|прогноз|пересмотр|наблюдени/ui', $name) !== 1
        ));
    }

    /**
     * Обе выгрузки отдают дату как "ДД.ММ.ГГГГ" — приводим к DATE-формату
     * MySQL. Пустое/нераспознанное значение — NULL, а не текущая дата или
     * иная догадка (current_ratings.last_action_date NOT NULL — вызывающий
     * код должен сам решить, пропускать ли строку без даты).
     */
    public static function parseDate(string $raw): ?string
    {
        $raw = trim($raw);
        if (!preg_match('/^(\d{2})\.(\d{2})\.(\d{4})$/', $raw, $m)) {
            return null;
        }

        [, $day, $month, $year] = $m;
        if (!checkdate((int) $month, (int) $day, (int) $year)) {
            return null;
        }

        return "{$year}-{$month}-{$day}";
    }

    /** @var array<string, int> сокращённое русское название месяца (нижний регистр) => номер */
    private const RUSSIAN_MONTHS = [
        'янв' => 1, 'фев' => 2, 'мар' => 3, 'апр' => 4,
        'май' => 5, 'июн' => 6, 'июл' => 7, 'авг' => 8,
        'сен' => 9, 'окт' => 10, 'ноя' => 11, 'дек' => 12,
    ];

    /**
     * АКРА отдаёт дату как "28 авг 2026" (день, сокращённое русское
     * название месяца, год) — не ДД.ММ.ГГГГ, как у НРА/НКР, отдельный
     * формат под отдельный метод, а не подгонка под parseDate().
     */
    public static function parseRussianMonthDate(string $raw): ?string
    {
        $raw = mb_strtolower(trim($raw));
        if (!preg_match('/^(\d{1,2})\s+([а-я]{3})[а-я]*\s+(\d{4})$/u', $raw, $m)) {
            return null;
        }

        [, $day, $monthAbbr, $year] = $m;
        $month = self::RUSSIAN_MONTHS[$monthAbbr] ?? null;
        if ($month === null || !checkdate($month, (int) $day, (int) $year)) {
            return null;
        }

        return sprintf('%04d-%02d-%02d', (int) $year, $month, (int) $day);
    }

    /**
     * xlsx хранит дату как порядковый номер дня (число дней с
     * 1899-12-30 — да, именно 30-е, из-за исторической ошибки Excel с
     * "1900 годом как високосным"; для дат после марта 1900 это не
     * влияет на результат). XlsxReader сам не преобразует форматы ячеек
     * (не разбирает styles.xml), поэтому для xlsx-источников, где дата
     * приходит именно так (см. ручной файл в STAGE3_RATINGS.md), нужен
     * отдельный разбор — не ДД.ММ.ГГГГ и не "28 авг 2026".
     */
    public static function parseExcelSerialDate(string $raw): ?string
    {
        $raw = trim($raw);
        if (!preg_match('/^\d+$/', $raw)) {
            return null;
        }

        $serial = (int) $raw;
        if ($serial < 1 || $serial > 100000) {
            return null;
        }

        $timestamp = ($serial - 25569) * 86400;

        return gmdate('Y-m-d', $timestamp);
    }

    /**
     * АКРА на странице списка рейтингуемых лиц (acra-ratings.ru/ratings/
     * issuers/, источник current_ratings для AcraImporter) иногда даёт
     * статус "под наблюдением" НЕ отдельной колонкой (как НРА) и не
     * глагольной прозой пресс-релиза/письма (как в AcraEmailParser), а
     * СЛИТНО, через запятую, прямо в значении прогноза: "Позитивный, под
     * наблюдением" / "Развивающийся, под наблюдением" — проверено вживую
     * на реальных примерах (сентябрь 2026: ООО «АЛЬФА-ЛИЗИНГ» и другие
     * строки того же списка). Без суффикса — поведение как у обычного
     * mapOutlook() (полностью обратная совместимость).
     *
     * "..., снято с наблюдения" в этом же слитном формате живьём НЕ
     * встретилось — обработано по аналогии с тем же правилом, что уже
     * есть у НРА (combineWithWatchStatus()): база есть → сама база,
     * базы нет → review_concluded. Непроверено вживую, помечено в докблоке
     * AcraImporter.
     */
    public static function combineOutlookWithAcraWatchSuffix(string $raw): ?string
    {
        $raw = trim($raw);

        if (preg_match('/^(.*?),\s*под\s+наблюдением\s*$/ui', $raw, $m)) {
            return self::combineWithWatch(self::mapOutlook(trim($m[1])), self::WATCH_ON);
        }

        if (preg_match('/^(.*?),\s*снято\s+с\s+наблюдения\s*$/ui', $raw, $m)) {
            return self::combineWithWatch(self::mapOutlook(trim($m[1])), self::WATCH_OFF);
        }

        return self::mapOutlook($raw);
    }

    /**
     * Ссылка к полному адресу: "ratings.ru/…" (выгрузка НКР отдаёт адреса
     * пресс-релизов без схемы — найдено 28.09.2026) → "https://ratings.ru/…",
     * путь от корня "/…" → "https://{$host}/…", "//host/…" → "https://host/…".
     * Не похоже на адрес — NULL.
     */
    public static function absoluteUrl(string $value, string $host): ?string
    {
        $value = trim($value);

        return match (true) {
            $value === '' => null,
            (bool) preg_match('~^https?://~i', $value) => $value,
            str_starts_with($value, '//') => 'https:' . $value,
            str_starts_with($value, '/') => "https://{$host}{$value}",
            (bool) preg_match('~^(?:www\.)?[a-z0-9-]+(?:\.[a-z0-9-]+)+/~i', $value) => 'https://' . $value,
            default => null,
        };
    }

    /**
     * Заголовки/подзаголовки новостей — не отдельное поле с одним словом
     * (как у mapOutlook()), а свободный текст с русскими падежными
     * окончаниями: "прогноз изменён на стабильный", "со стабильным
     * прогнозом", "прогноз — стабильный" — все варианты одного слова
     * должны дать один результат. Поэтому здесь — поиск по корню слова,
     * а не точное совпадение всей строки. Как и mapOutlook() — честный
     * NULL для всего, что не сводится к одному из 4 базовых значений.
     * Статус "на пересмотре" ("рейтинг на пересмотре с возможностью
     * понижения" и т.п.) сюда не относится — отдельная, более
     * специфичная категория, см. extractReviewStatusFromProse(), которую
     * вызывающий код должен проверить ПЕРЕД этим методом.
     */
    public static function mapOutlookFromProse(string $text): ?string
    {
        $text = mb_strtolower($text);

        return match (true) {
            (bool) preg_match('/позитивн|положительн/u', $text) => 'positive',
            (bool) preg_match('/негативн|отрицательн/u', $text) => 'negative',
            (bool) preg_match('/стабильн/u', $text) => 'stable',
            (bool) preg_match('/развивающ/u', $text) => 'developing',
            // Отдельный код — см. mapOutlook() и миграцию 026.
            (bool) preg_match('/неопределенн|неопределённ/u', $text) => 'indefinite',
            default => null,
        };
    }

    /**
     * У НКР одно и то же "текущий рейтинг отозван" пишется в
     * current_ratings.rating ДВУМЯ разными импортёрами по-разному:
     * NkrNewsImporter (через NkrTitleParser::extractRatingChange()) для
     * глагола "отозвало" пишет наш собственный литерал 'отозван', а
     * NkrImporter (полная Excel-выгрузка ratings.ru/issuers.php) раньше
     * копировал колонку "Rating" дословно как есть — если сам НКР пишет
     * там "Рейтинг отозван" (а не просто "отозван"), то у одного и того
     * же эмитента текст в current_ratings.rating зависел от того, какой
     * из двух импортёров прогонялся последним (оба пишут в один
     * ON DUPLICATE KEY UPDATE) — архитектурная нестыковка, найденная
     * пользователем, не разовый баг. Нормализуем текст отзыва здесь, в
     * ОДНОМ месте: любое написание со словом "отозван" (падеж/порядок
     * слов не важны) сводится к тому же самому литералу 'отозван', что
     * уже год пишет NkrNewsImporter — оба импортёра теперь дают
     * одинаковое значение независимо от порядка прогонов.
     */
    public static function normalizeWithdrawnRatingText(string $raw): string
    {
        $trimmed = trim($raw);
        if (preg_match('/отозван/ui', $trimmed)) {
            return 'отозван';
        }

        return mb_substr($trimmed, 0, 20);
    }

    /**
     * Реальный найденный баг (17 сентября 2026, живая находка пользователя
     * на АКРА, но конструкция ("рейтинг ВЫПУСКА ОБЛИГАЦИЙ" + "в связи с
     * погашением") не специфична для одного агентства — НКР даже заранее
     * предвидел этот случай в докблоке NkrTitleParser, просто не обрабатывал
     * его): "АКРА ОТОЗВАЛО КРЕДИТНЫЙ РЕЙТИНГ ВЫПУСКА ОБЛИГАЦИЙ ПАО
     * «ФОСАГРО» СЕРИИ БО-П02 (RU000A109K40) В СВЯЗИ С ПОГАШЕНИЕМ ВЫПУСКА".
     *
     * Это НЕ отзыв кредитного рейтинга ЭМИТЕНТА (реальное, значимое
     * событие) — это техническое снятие рейтинга с КОНКРЕТНОГО ВЫПУСКА
     * облигаций ровно потому, что сам выпуск погашен и рейтинговать
     * больше нечего. Раньше (extractGrade()/extractRatingChange() для
     * глагола "отозвал(о)") оба случая писали один и тот же литерал
     * 'отозван' в current_ratings — а current_ratings хранит ОДНУ строку
     * на пару (issuer_id, agency), т.е. "эмитентский" общий рейтинг.
     * Итог: у эмитента с реальным действующим кредитным рейтингом при
     * погашении ОДНОЙ его облигационной серии в current_ratings ложно
     * появлялось "рейтинг отозван" — хотя у самой компании рейтинг никуда
     * не делся.
     *
     * Решение пользователя: такие строки — чистый шум, не несущий
     * никакой информации о реальном кредитном качестве эмитента,
     * полностью исключаются из БД (rating_actions/events/current_ratings
     * не создаются вообще), а не просто помечаются как ошибка разбора.
     *
     * Специфично для ВЫПУСКА (не эмитента в целом) — "рейтинг(а) выпуска
     * облигаций" (падежные окончания не важны) — И одновременно упоминает
     * погашение где-то в заголовке. Оба условия вместе — узкая, почти
     * наверняка однозначная комбинация: отзыв рейтинга ЭМИТЕНТА (не
     * выпуска) по любой другой причине этот метод не заденет, а отзыв
     * рейтинга выпуска НЕ из-за погашения (гипотетически — по другой
     * причине) тоже не заденет, раз слова "погашен..." в заголовке нет.
     * Не привязано к конкретному глаголу/агентству намеренно — вызывающий
     * код (each *NewsImporter::importRow()) дополнительно проверяет, что
     * само действие — именно отзыв (verb начинается с "отозвал"), это
     * решение уровня импортёра, не этого чистого текстового метода.
     *
     * "Рейтинг выпуска" определяется общим isBondIssueRatingTitle() — в
     * том числе формулировка без слова "выпуск" ("отозвал рейтинг
     * облигаций серии X в связи с погашением"), которую прежний шаблон
     * пропускал.
     */
    public static function isBondIssueRedemptionWithdrawal(string $title): bool
    {
        return self::isBondIssueRatingTitle($title) && (bool) preg_match('/погашен/u', mb_strtolower($title));
    }

    /**
     * Заголовок про рейтинг ОБЛИГАЦИЙ (конкретного выпуска), а не
     * компании. Проверено на реальных заголовках (сентябрь 2026):
     *   - "НКР присвоило выпуску биржевых облигаций ООО «Мэйл.Ру Финанс»
     *     серии 001P-04 кредитный рейтинг AA.ru" (выпуск назван ДО слова
     *     "рейтинг");
     *   - "«Эксперт РА» подтвердил кредитные рейтинги облигаций АО «АБЗ-1»",
     *     "…по кредитному рейтингу облигаций АО «ПКТ» серии 002P-01";
     *   - "КРЕДИТНЫЙ РЕЙТИНГ ВЫПУСКА ОБЛИГАЦИЙ ПАО «ФОСАГРО»",
     *     "рейтинг облигационного выпуска".
     * Выпуск, упомянутый ПОСЛЕ слова "рейтинг" без прямой связи с ним
     * ("отозвало кредитный рейтинг ООО «Х» в связи с погашением выпуска
     * облигаций"), сюда не попадает — это рейтинг компании.
     */
    public static function isBondIssueRatingTitle(string $title): bool
    {
        // До трёх прилагательных между "рейтинг"/"выпуск" и "облигаций" —
        // любых, по окончанию прилагательного, а не по списку: 28.09.2026
        // "рейтинг субординированных облигаций Банка ГПБ" проскакивал мимо
        // фильтра погашения, 29.09.2026 "выпуску биржевых зелёных облигаций
        // АО «СТМ»" не узнавался сверкой как рейтинг облигаций. Названия
        // компаний и местоимения ("банка", "его", «Х») окончаний
        // прилагательного не имеют — новость про компанию не цепляется.
        // Плюс "рейтинг инструмента структурированного финансирования облигаций".
        $adjectives = '(?:[а-яё]+(?:ых|ым|ыми|их|им|ими|ого|ой|ую|ая|ые|ие|ий|ый)\s+){0,3}';
        $instrument = '(?:инструмент[а-яё]*\s+структурированн[а-яё]*\s+финансировани[а-яё]*\s+)?';

        return (bool) preg_match(
            "/рейтинг[а-яё]*\s+(?:по\s+)?{$instrument}(?:выпуск[а-яё]*\s+)?{$adjectives}облигаци"
            . '|рейтинг[а-яё]*\s+(?:по\s+)?облигационн[а-яё]*\s+выпуск'
            . "|выпуск[а-яё]*\s+{$adjectives}облигаци.*рейтинг/u",
            mb_strtolower($title)
        );
    }

    /**
     * Отзыв рейтинга ОБЛИГАЦИЙ, который не должен влиять на рейтинг
     * компании (решение пользователя, 28.09.2026) — общий для новостей
     * НКР, Эксперт РА и АКРА. Вызывающий код проверяет, что действие —
     * отзыв. Срабатывает, только если новость про облигации/выпуск (не про
     * компанию), и причина одна из:
     *   - погашение (полное, досрочное) — как раньше;
     *   - выпуск не размещён: "отсутствием размещения облигаций в течение
     *     года" (ПАО «Банк ПСБ»), "решением об отказе от размещения"
     *     (Республика Башкортостан), "решение не размещать";
     *   - отзывается ОЖИДАЕМЫЙ рейтинг / облигации "планируемые к выпуску" —
     *     по определению выпуск ещё не размещён, причина не важна.
     * Отзыв облигаций по другим причинам (истёк/расторгнут договор) — НЕ
     * пропускается: у компании, от которой у нас есть только рейтинг
     * облигаций (ВСК, АБЗ-1, ПКТ), это и есть отзыв; у остальных агентство
     * в тот же день отдельно отзывает рейтинг компании (Селектел, О'КЕЙ,
     * ТрансФин-М, Томская область — проверено на ленте Эксперт РА).
     * Отзыв рейтинга самой компании ("в связи с погашением задолженности")
     * не задевается никогда.
     */
    public static function isNeutralBondWithdrawal(string $text): bool
    {
        $lower = mb_strtolower($text);
        $planned = (bool) preg_match('/планируем[а-яё]*\s+к\s+выпуск/u', $lower);
        if (!self::isBondIssueRatingTitle($text) && !$planned) {
            return false;
        }

        return $planned
            || (bool) preg_match(
                // "от размещения" — всегда отказ: "решением об отказе от
                // размещения", "в связи с отказом эмитента от размещения".
                '/ожидаем[а-яё]*\s+(?:кредитн[а-яё]*\s+)?рейтинг|погашен|не\s+размещ|неразмещ|от\s+размещени|отсутстви[а-яё]*\s+размещ/u',
                $lower
            );
    }

    /**
     * Общее решение для новостей НКР, Эксперт РА и АКРА: пропустить
     * новость про облигации, которая не должна влиять на рейтинг компании,
     * и с каким статусом записать её в rating_news_log (миграция 026). NULL
     * — не пропускать. Предмет новости (облигации или компания) —
     * по заголовку; причина отзыва — по всему тексту (у Эксперт РА она
     * часто только в подзаголовке).
     *   - skipped_subordinated — рейтинг субординированных облигаций, любое
     *     действие;
     *   - skipped_expected — ожидаемый рейтинг облигаций (присвоение,
     *     подтверждение, отзыв — любое действие; решение пользователя
     *     28.09.2026): выпуск ещё не размещён, итоговый рейтинг придёт после
     *     размещения (ТБанк: ожидаемый 04.09 → итоговый 15.09; Мэйл.Ру
     *     Финанс: eAA.ru 15.09 → AA.ru 22.09). Раньше записывался как рейтинг
     *     компании с пометкой "(EXP)"/"e…" (у Эксперт РА 63 из 946 новостей,
     *     у НКР 15 из 1069);
     *   - skipped_bond_redemption — отзыв из-за погашения;
     *   - skipped_bond_not_placed — отзыв из-за неразмещения.
     */
    public static function bondNewsSkipStatus(string $title, string $fullText, bool $isWithdrawal): ?string
    {
        $isBondNews = self::isBondIssueRatingTitle($title)
            || (bool) preg_match('/планируем[а-яё]*\s+к\s+выпуск/u', mb_strtolower($title));
        if (!$isBondNews) {
            return null;
        }
        if (self::isSubordinatedBondRating($title)) {
            return 'skipped_subordinated';
        }
        if (self::isExpectedRatingTitle($title)) {
            return 'skipped_expected';
        }
        if (!$isWithdrawal) {
            return null;
        }
        if (preg_match('/погашен/u', mb_strtolower($fullText))) {
            return 'skipped_bond_redemption';
        }

        return self::isNeutralBondWithdrawal($title . ' ' . $fullText) ? 'skipped_bond_not_placed' : null;
    }

    /**
     * bondNewsSkipStatus() для уже сохранённой новости — есть только
