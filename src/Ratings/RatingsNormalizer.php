<?php

declare(strict_types=1);

namespace BondKeeper\Ratings;

/**
 * Общие для НРА/НКР (и, вероятно, будущих агентств) преобразования сырых
 * текстовых значений из выгрузок в формат схемы БД. Вынесено в отдельный
 * класс, а не продублировано в каждом импортёре — вокабуляр прогноза на
 * русском совпадает у обоих агентств, дата в обоих выгрузках — DD.MM.YYYY.
 */
final class RatingsNormalizer
{
    /**
     * current_ratings.outlook — ENUM('positive','stable','negative','developing',
     * 'under_review'/'under_review_negative'/'under_review_positive'/
     * 'under_review_stable'/'under_review_developing'/'review_concluded',
     * см. миграцию 017). Этот метод — только 4 "базовых" направления;
     * статус "на пересмотре"/"под наблюдением" собирается ОТДЕЛЬНО (см.
     * combineWithWatchStatus() для НРА, extractReviewStatusFromProse() для
     * НКР) — не здесь, чтобы не разрастить один exact-match на десяток
     * составных случаев. Для всего, что не сводится однозначно к одному
     * из 4 базовых значений, — честно NULL, а не приблизительная догадка.
     */
    public static function mapOutlook(string $raw): ?string
    {
        return match (mb_strtolower(trim($raw))) {
            'стабильный' => 'stable',
            'позитивный' => 'positive',
            'негативный' => 'negative',
            'неопределенный', 'неопределённый' => 'developing',
            // АКРА использует "развивающийся" там, где остальные говорят
            // "неопределённый" — тот же смысл (S&P-style "developing"),
            // другое слово (см. STAGE3_RATINGS.md, JSON-выгрузка АКРА).
            'развивающийся' => 'developing',
            default => null,
        };
    }

    /**
     * НРА иногда (не всегда — см. combineWithWatchStatus()) дублирует
     * статус наблюдения прямо в тексте колонки "Прогноз": "Стабильный -
     * под наблюдением", "Без прогноза - снято с наблюдения". Отрезаем
     * этот суффикс, чтобы БАЗОВОЕ направление (до дефиса) всё равно
     * прошло через обычный mapOutlook() — статус наблюдения учитывается
     * отдельно, по колонке "Под наблюдением" (надёжнее свободного текста).
     */
    public static function stripWatchSuffix(string $raw): string
    {
        return trim(preg_replace('/\s*-\s*(под наблюдением|снято с наблюдения)\s*$/ui', '', $raw) ?? $raw);
    }

    /**
     * НРА даёт статус "на пересмотре" СТРУКТУРИРОВАННО — отдельной
     * колонкой "Под наблюдением" (значения: "", "Под наблюдением", "Снято
     * с наблюдения"; проверено на живой выгрузке — 130/209/602 строк
     * соответственно), а не свободным текстом, как НКР. Это надёжнее:
     * не нужно парсить формулировки — просто три известных значения.
     *
     * $baseOutlook — результат mapOutlook(stripWatchSuffix($raw['Прогноз']))
     * — базовое направление ДО учёта статуса наблюдения.
     *
     * Правила (решение пользователя, сентябрь 2026, на реальных данных —
     * ни разу не встретилось "Позитивный"/"Негативный" в сочетании с
     * "под наблюдением" в колонке "Прогноз" НРА, поэтому under_review_
     * positive/negative для НРА пока чисто гипотетические, но обработаны
     * той же веткой на случай, если встретятся):
     *   - "Под наблюдением" + база → under_review[_negative|_positive|
     *     _stable|_developing], без базы → under_review (голое).
     *   - "Снято с наблюдения" + база есть → сама база (наблюдение снято,
     *     это уже обычный прогноз); базы нет (только этот случай
     *     реально встретился — "Без прогноза - снято с наблюдения") →
     *     review_concluded — пользователь явно попросил отдельное
     *     значение, не молчаливый NULL: сам факт "снято этим действием"
     *     значим, даже когда текущий прогноз не назван.
     *   - "" (не под наблюдением вообще) → база как есть, без изменений.
     */
    public static function combineWithWatchStatus(?string $baseOutlook, string $watchColumnRaw): ?string
    {
        return match (mb_strtolower(trim($watchColumnRaw))) {
            'под наблюдением' => match ($baseOutlook) {
                'negative' => 'under_review_negative',
                'positive' => 'under_review_positive',
                'stable' => 'under_review_stable',
                'developing' => 'under_review_developing',
                default => 'under_review',
            },
            'снято с наблюдения' => $baseOutlook ?? 'review_concluded',
            default => $baseOutlook,
        };
    }

    /**
     * НКР статус "на пересмотре" даёт только свободным текстом заголовка
     * (нет отдельной структурированной колонки, в отличие от НРА) —
     * "рейтинг на пересмотре с возможностью понижения/повышения" или
     * просто "на пересмотре" без уточнения направления. Проверяется
     * ДО обычного mapOutlookFromProse() — это отдельный, более
     * специфичный статус, не сводится к 4 базовым направлениям.
     */
    public static function extractReviewStatusFromProse(string $text): ?string
    {
        $text = mb_strtolower($text);
        if (!preg_match('/на пересмотре|под наблюдением/u', $text)) {
            return null;
        }

        return match (true) {
            (bool) preg_match('/возможностью понижения|возможностью снижения/u', $text) => 'under_review_negative',
            (bool) preg_match('/возможностью повышения/u', $text) => 'under_review_positive',
            default => 'under_review',
        };
    }

    /**
     * Эксперт РА даёт статус "под наблюдением" СВОЕЙ терминологией — не
     * "на пересмотре" (НКР), не структурированной колонкой (НРА), а
     * собственными глагольными оборотами в тексте (проверено вживую на
     * 18 реальных примерах, сентябрь 2026):
     *   - "установил статус «под наблюдением»" — статус НАЧАТ (обычно
     *     вместе с "присвоил" — новый рейтинг сразу под наблюдением);
     *   - "продлил статус «под наблюдением»" — статус ПРОДЛЁН (свой
     *     отдельный глагол — см. добавление "продлил" в
     *     ExpertRaNewsImporter::VERBS);
     *   - "снял статус «под наблюдением»" — статус ЗАВЕРШЁН.
     * Направление (positive/negative) в этой формулировке НИ РАЗУ не
     * встретилось явно — всегда общая фраза "означает высокую вероятность
     * рейтинговых действий в ближайшее время", без уточнения "в какую
     * сторону". Поэтому "установил"/"продлил" здесь ВСЕГДА даёт голое
     * under_review, без directional-вариантов (в отличие от НКР/НРА, где
     * направление иногда есть).
     *
     * "Снял" обрабатывается тем же правилом, что и у НРА
     * (combineWithWatchStatus): $baseOutlook уже вычислен вызывающим
     * кодом (обычный прогноз ИЗ ЭТОГО ЖЕ действия, если он был назван) —
     * если есть, он и остаётся; если нет — review_concluded.
     *
     * Возвращает NULL, если про статус наблюдения в тексте вообще ничего
     * нет — тогда вызывающий код использует $baseOutlook как есть.
     */
    public static function extractWatchStatusFromExpertRaProse(string $text, ?string $baseOutlook): ?string
    {
        $text = mb_strtolower($text);
        if (preg_match('/снял\s+статус\s*«?под\s+наблюдением»?/u', $text)) {
            return $baseOutlook ?? 'review_concluded';
        }
        if (preg_match('/(установил|продлил)\s+статус\s*«?под\s+наблюдением»?/u', $text)) {
            return 'under_review';
        }

        return null;
    }

    /**
     * Защитный барьер против нестандартных шкал (суффикс "sf" —
     * structured finance). Изначально написан для НКР (где вживую не
     * встретился ни разу), но подтвердился РЕАЛЬНО нужным для Эксперт РА
     * (сентябрь 2026, живая лента: "...на уровне ruAAA.sf" — 12 из 200
     * проверенных новостей) — Эксперт РА рейтингует структурированное
     * финансирование, и без этого барьера ".sf" отбрасывался бы молча
     * (общий регэксп грейда останавливается на точке и извлёк бы просто
     * "ruAAA", как будто это обычный корпоративный рейтинг). Вынесен сюда
     * из NkrTitleParser, когда понадобился второму агентству — общая,
     * не специфичная для НКР проверка.
     *
     * Проверка по целому слову ("\bsf\b"), не по подстроке — случайное
     * совпадение в русском тексте практически исключено.
     */
    public static function isNonStandardRating(string $title): bool
    {
        return (bool) preg_match('/\bsf\b/ui', $title);
    }

    /**
     * Все названия в «ёлочках» из заголовка, без дублей, в порядке
     * появления. Общий метод для НКР и Эксперт РА — оба кладут в кавычки
     * названия юрлиц в заголовках пресс-релизов/новостей (номера серий
     * облигаций, даты и т.п. в кавычки не попадают).
     *
     * Два реальных найденных вживую случая, ломающих наивное допущение
     * "в кавычках — всегда название компании", оба закрыты одним и тем же
     * фильтром:
     *   - НКР: "...ООО «ЛКХ» с B.ru до CC.ru, прогноз — «рейтинг на
     *     пересмотре с возможностью понижения»" — вторая пара кавычек
     *     цитирует статус прогноза, не компанию;
     *   - Эксперт РА: "...и снял статус «под наблюдением»" — та же
     *     история, другая формулировка статуса.
     * Отсекаем такие кандидаты двумя эвристиками: 1) название юрлица
     * всегда начинается с заглавной буквы, цитата статуса — со строчной;
     * 2) дополнительно отсекаем кандидатов со словами
     * "рейтинг/прогноз/пересмотр/наблюдени" (в названии реальной компании
     * такие слова практически невозможны).
     *
     * Эксперт РА, в отличие от НКР, непоследователен в стиле кавычек —
     * часть названий в «ёлочках» (основной, регулярный стиль), но
     * заметная доля — в ПРЯМЫХ кавычках: `ООО "Сибэнергомаш - БКЗ"`,
     * `АО "АБЗ-1"`, `ПАО "РусГидро"` (проверено вживую, сентябрь 2026 —
     * без учёта прямых кавычек порядка 20% реальных новостей уходили в
     * "не сопоставлено", хотя компания есть в тексте). Оба стиля
     * собираются и объединяются здесь. Известное ограничение, не
     * решаемое кавычками вообще: часть названий (обычно регионы/
     * субъекты РФ — "Ульяновской области", "Республики Башкортостан" —
     * и один случай ALL CAPS без кавычек, "АО РОСЭКСИМБАНК") не берутся
     * в кавычки НИКАКОГО стиля — не резолвятся этим методом в принципе;
     * для BondKeeper (фокус на корпоративных облигациях, не суверенном/
     * субфедеральном долге) это, по всей видимости, не критично.
     *
     * @return array<int, string>
     */
    public static function extractQuotedNames(string $title): array
    {
        preg_match_all('/«([^»]+)»/u', $title, $m1);
        preg_match_all('/"([^"]+)"/u', $title, $m2);
        $names = array_values(array_unique(array_merge($m1[1], $m2[1])));

        return array_values(array_filter(
            $names,
            static fn (string $name): bool => preg_match('/^[A-ZА-ЯЁ]/u', $name) === 1
                && preg_match('/рейтинг|прогноз|пересмотр|наблюдени/ui', $name) !== 1
        ));
    }

    /**
     * Обе выгрузки отдают дату как "ДД.ММ.ГГГГ" — приводим к DATE-формату
     * MySQL. Пустое/нераспознанное значение — NULL, а не текущая дата или
     * иная догадка (current_ratings.last_action_date NOT NULL — вызывающий
     * код должен сам решить, пропускать ли строку без даты).
     */
    public static function parseDate(string $raw): ?string
    {
        $raw = trim($raw);
        if (!preg_match('/^(\d{2})\.(\d{2})\.(\d{4})$/', $raw, $m)) {
            return null;
        }

        [, $day, $month, $year] = $m;
        if (!checkdate((int) $month, (int) $day, (int) $year)) {
            return null;
        }

        return "{$year}-{$month}-{$day}";
    }

    /** @var array<string, int> сокращённое русское название месяца (нижний регистр) => номер */
    private const RUSSIAN_MONTHS = [
        'янв' => 1, 'фев' => 2, 'мар' => 3, 'апр' => 4,
        'май' => 5, 'июн' => 6, 'июл' => 7, 'авг' => 8,
        'сен' => 9, 'окт' => 10, 'ноя' => 11, 'дек' => 12,
    ];

    /**
     * АКРА отдаёт дату как "28 авг 2026" (день, сокращённое русское
     * название месяца, год) — не ДД.ММ.ГГГГ, как у НРА/НКР, отдельный
     * формат под отдельный метод, а не подгонка под parseDate().
     */
    public static function parseRussianMonthDate(string $raw): ?string
    {
        $raw = mb_strtolower(trim($raw));
        if (!preg_match('/^(\d{1,2})\s+([а-я]{3})[а-я]*\s+(\d{4})$/u', $raw, $m)) {
            return null;
        }

        [, $day, $monthAbbr, $year] = $m;
        $month = self::RUSSIAN_MONTHS[$monthAbbr] ?? null;
        if ($month === null || !checkdate($month, (int) $day, (int) $year)) {
            return null;
        }

        return sprintf('%04d-%02d-%02d', (int) $year, $month, (int) $day);
    }

    /**
     * xlsx хранит дату как порядковый номер дня (число дней с
     * 1899-12-30 — да, именно 30-е, из-за исторической ошибки Excel с
     * "1900 годом как високосным"; для дат после марта 1900 это не
     * влияет на результат). XlsxReader сам не преобразует форматы ячеек
     * (не разбирает styles.xml), поэтому для xlsx-источников, где дата
     * приходит именно так (см. ручной файл в STAGE3_RATINGS.md), нужен
     * отдельный разбор — не ДД.ММ.ГГГГ и не "28 авг 2026".
     */
    public static function parseExcelSerialDate(string $raw): ?string
    {
        $raw = trim($raw);
        if (!preg_match('/^\d+$/', $raw)) {
            return null;
        }

        $serial = (int) $raw;
        if ($serial < 1 || $serial > 100000) {
            return null;
        }

        $timestamp = ($serial - 25569) * 86400;

        return gmdate('Y-m-d', $timestamp);
    }

    /**
     * Заголовки/подзаголовки новостей — не отдельное поле с одним словом
     * (как у mapOutlook()), а свободный текст с русскими падежными
     * окончаниями: "прогноз изменён на стабильный", "со стабильным
     * прогнозом", "прогноз — стабильный" — все варианты одного слова
     * должны дать один результат. Поэтому здесь — поиск по корню слова,
     * а не точное совпадение всей строки. Как и mapOutlook() — честный
     * NULL для всего, что не сводится к одному из 4 базовых значений.
     * Статус "на пересмотре" ("рейтинг на пересмотре с возможностью
     * понижения" и т.п.) сюда не относится — отдельная, более
     * специфичная категория, см. extractReviewStatusFromProse(), которую
     * вызывающий код должен проверить ПЕРЕД этим методом.
     */
    public static function mapOutlookFromProse(string $text): ?string
    {
        $text = mb_strtolower($text);

        return match (true) {
            (bool) preg_match('/позитивн|положительн/u', $text) => 'positive',
            (bool) preg_match('/негативн|отрицательн/u', $text) => 'negative',
            (bool) preg_match('/стабильн/u', $text) => 'stable',
            (bool) preg_match('/развивающ|неопределенн|неопределённ/u', $text) => 'developing',
            default => null,
        };
    }
}
