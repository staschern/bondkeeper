<?php

declare(strict_types=1);

namespace BondKeeper\Ratings;

use BondKeeper\Iss\IssuerNameShortener;
use PDO;

/**
 * Сопоставление эмитента с сайта агентства с issuers.id.
 *
 * Изначально (см. docs/STAGE3_RATINGS.md, раздел про риск сопоставления)
 * предполагалось, что понадобится нечёткое сопоставление по названию —
 * на страницах списка рейтингов ИНН не показывается. На всех источниках
 * "текущих рейтингов" (current_ratings) ИНН всё же нашёлся напрямую тем
 * или иным путём — там матчер работал только по ИНН.
 *
 * Для парсинга НОВОСТЕЙ (rating_actions) реальная необходимость всё же
 * возникла: у Эксперт РА в ленте пресс-релизов эмитент виден только по
 * названию в тексте новости, ИНН там не даётся вообще (в отличие от
 * страницы конкретной компании, которая используется для current_ratings).
 * По прямому указанию пользователя — точное сопоставление по названию
 * (после нормализации: без кавычек/организационно-правовой формы/
 * регистра), НЕ приблизительное/расстояние Левенштейна и т.п. — как
 * запасной вариант, когда ИНН взять неоткуда.
 *
 * Ошибка сопоставления здесь хуже, чем где-либо ещё в проекте — молча
 * приписывает рейтинг не той компании. Поэтому: не находим — не пишем
 * строку вообще, эмитент попадает в отчёт "не сопоставлено", а не
 * привязывается по эвристике.
 *
 * === Третий уровень — "по корню" названия, для SPV (сентябрь 2026) ===
 *
 * По прямому запросу пользователя: считаем, что материнская компания и
 * её SPV "для привлечения долга" по кредитному риску РАВНЫ, поэтому если
 * в issuers заведена только ОДНА из двух сторон (например, только
 * SPV «Ростелеком Финанс», а рейтинговое агентство пишет новость только
 * про «Ростелеком»), а источник называет ТОЛЬКО ДРУГУЮ — findIssuerIdByInn()
 * и findIssuerIdByName() выше ничего не найдут (разные ИНН, разное точное
 * название). findIssuerIdByRootName() — третий, ПОСЛЕДНИЙ fallback,
 * пробуется вызывающим кодом, только когда первые два не дали результата:
 * снимает с обеих сторон сравнения ещё и типовые слова-маркеры SPV
 * (Финанс/Капитал), чтобы «Ростелеком» и «Ростелеком Финанс» свелись к
 * одному и тому же "корню". Самый неточный из трёх — те же гарантии
 * "не угадываем" (неоднозначность, минимальная длина корня), что и у
 * findIssuerIdByName().
 */
final class IssuerMatcher
{
    /**
     * Типовые слова-маркеры SPV "для привлечения долга" — по прямому
     * запросу пользователя (сентябрь 2026, см. кейс "ООО-пустышка для
     * привлечения долга" в docs/STAGE3_RATINGS.md). Список пополняется по
     * факту реальных находок (тот же принцип, что уже применялся для ОПФ
     * в normalizeCompanyName() и для нестандартных шкал рейтинга (".sf" и
     * т.п.) в других частях проекта) — "ГРУПП" добавлено по реальному
     * найденному случаю: НКР 14.11.2025 присвоило рейтинг ООО «Аэрофьюэлз
     * Групп» (SPV, ИНН 7710380617, в issuers не заведён) и ОДНОВРЕМЕННО
     * подтвердило рейтинг облигаций АО «Аэрофьюэлз» (материнская, ИНН
     * 7714216826, в issuers ЕСТЬ) — связь между ними в БД тогда
     * установилась только благодаря тому, что оба имени были в ОДНОМ
     * заголовке (точное совпадение по имени «Аэрофьюэлз» сработало само).
     * Без "ГРУПП" в этом списке любое БУДУЩЕЕ действие, где НКР назовёт
     * только SPV (без повторного упоминания материнской компании в том же
     * заголовке), прошло бы мимо — ни по ИНН (разные лица), ни по точному
     * имени ("Аэрофьюэлз Групп" ≠ "Аэрофьюэлз"), ни по корню без этого
     * слова в списке. Не "ГРУППА" (это форма уже снимается ОПФ-словарём
     * normalizeCompanyName() ) — а именно "ГРУПП" без окончания
     * (англицированный стиль вида "Х5 Групп"), это другой токен.
     */
    private const ROOT_MARKER_WORDS = ['ФИНАНС', 'КАПИТАЛ', 'ГРУПП'];

    /**
     * Минимальная длина "корня" после снятия ОПФ и маркерного слова — по
     * прямому указанию пользователя. Короче — не считаем корнем вообще
     * (возвращаем ''), слишком велик риск случайного совпадения с чем-то
     * не тем.
     */
    private const MIN_ROOT_LENGTH = 3;

    /** @var array<string, int>|null нормализованное имя => issuer_id, строится один раз на прогон */
    private ?array $nameIndex = null;

    /** @var array<string, int>|null "корень" названия => issuer_id, строится один раз на прогон */
    private ?array $rootIndex = null;

    public function __construct(
        private readonly PDO $db,
    ) {
    }

    public function findIssuerIdByInn(?string $rawInn): ?int
    {
        $inn = self::normalizeInn($rawInn);
        if ($inn === null) {
            return null;
        }

        $stmt = $this->db->prepare('SELECT id FROM issuers WHERE inn = :inn');
        $stmt->execute(['inn' => $inn]);
        $id = $stmt->fetchColumn();

        return $id !== false ? (int) $id : null;
    }

    /**
     * Явная, вручную заведённая связка "неизвестный ИНН → issuer_id,
     * который реально есть в БД" (`issuer_spv_links`, миграция 023) — по
     * прямому запросу пользователя (сентябрь 2026).
     *
     * ВАЖНО про сам критерий (найдено методом проб и ошибок, сентябрь
     * 2026 — несколько раз перепутали направление в разговоре с
     * пользователем, пока не сформулировали чётко): "spv_inn"/"issuer_id"
     * — это НЕ "ИНН SPV" и "issuer_id материнской компании" в смысле
     * реальной корпоративной структуры. Кто из двух юрлиц "по смыслу"
     * мать/поручитель, а кто — SPV/эмитент облигаций, для этого метода
     * НЕ ИМЕЕТ ЗНАЧЕНИЯ и совершенно не обязано совпадать с тем, что уже
     * есть в issuers. Единственный реальный критерий:
     *   - spv_inn — ИНН той стороны, которой НЕТ в issuers (тот, что
     *     пришёл с источника — новости/выгрузки — и не находится ни по
     *     ИНН, ни по имени, ни по корню);
     *   - issuer_id — та сторона, которая УЖЕ ЕСТЬ в issuers (обычно
     *     потому, что именно она физически выпускает облигации на бирже
     *     — но это тоже не гарантия, а лишь типичная причина).
     * Реальный найденный пример, где интуиция "мать = уже в issuers"
     * подвела: ООО «ФСК Активы» (ИНН 7714482955) есть в issuers (её
     * облигации торгуются на бирже), а ООО «ЕВА» (ИНН 7708335695) —
     * НЕТ, хотя структурно именно ЕВА — поручитель, которого рейтингует
     * агентство напрямую ("Информация о рейтингуемом лице: ООО «ЕВА»"
     * на детальной странице пресс-релиза, при этом «ФСК Активы»
     * упоминается только в связи с выпуском облигаций). Связка здесь:
     * spv_inn=7708335695 (ЕВА, её нет в issuers) → issuer_id «ФСК
     * Активы» (она есть). Аналогично: spv_inn=2315190775 (АгроНэкст, её
     * нет в issuers) → issuer_id «Русбонд-Удобрения» (она есть, её
     * облигации на бирже). Имена в обеих парах НЕ ИМЕЮТ НИЧЕГО ОБЩЕГО —
     * ни ИНН, ни точное имя, ни "по корню" (findIssuerIdByRootName(),
     * снятие ОПФ/маркерных слов) их в принципе связать не может, это не
     * вариации одного названия, а два независимых бренда. Единственный
     * способ — человек один раз явно указывает связь (по аналогии с
     * ManualRatingsImporter: "то, что автоматика не находит сама,
     * добавляет пользователь").
     *
     * В отличие от findIssuerIdByRootName() — это НЕ эвристика, а
     * подтверждённый человеком факт, поэтому проверяется СРАЗУ после
     * собственного ИНН кандидата (который, естественно, никогда не
     * найдётся в issuers напрямую — иначе связка вообще не понадобилась
     * бы) — ПЕРЕД точным именем и корнем, а не после них. Ошибиться здесь
     * может только опечатка при заполнении таблицы (в т.ч. перепутанное
     * направление — см. выше), не логика сопоставления — поэтому никакой
     * пометки для выборочной проверки (как matched_by_root_name) не
     * требуется.
     */
    public function findIssuerIdBySpvLink(?string $rawInn): ?int
    {
        $inn = self::normalizeInn($rawInn);
        if ($inn === null) {
            return null;
        }

        $stmt = $this->db->prepare('SELECT issuer_id FROM issuer_spv_links WHERE spv_inn = :spv_inn');
        $stmt->execute(['spv_inn' => $inn]);
        $id = $stmt->fetchColumn();

        return $id !== false ? (int) $id : null;
    }

    /**
     * Сопоставление по ISIN конкретного выпуска (securities.isin, УНИКАЛЬНЫЙ
     * ключ, миграция 001) — добавлено для АКРА (ШАБЛОН, сентябрь 2026,
     * не проверено на реальной БД): часть их писем даёт рейтинг КОНКРЕТНОГО
     * выпуска облигаций с указанием ISIN прямо в тексте (см.
     * AcraEmailParser/AcraMailImporter), а не название компании в кавычках.
     * Это единственный источник в проекте, где нашёлся такой путь —
     * потенциально закрывает категорию "регион/субъект РФ без ИНН и без
     * кавычек", которая у Эксперт РА была принципиально нерешаемой (сама
     * бумага регистрируется на конкретного эмитента даже тогда, когда у
     * него, как у муниципалитета, нет ИНН юрлица в привычном смысле).
     * ISIN присутствует НЕ в каждом письме АКРА даже для одного и того же
     * выпуска (см. докблок AcraEmailParser) — поэтому это ЗАПАСНОЙ путь
     * наравне с сопоставлением по имени, не замена ему.
     */
    public function findIssuerIdByIsin(?string $rawIsin): ?int
    {
        $isin = $rawIsin !== null ? mb_strtoupper(trim($rawIsin)) : null;
        if ($isin === null || !preg_match('/^[A-Z]{2}[A-Z0-9]{9}\d$/', $isin)) {
            return null;
        }

        $stmt = $this->db->prepare('SELECT issuer_id FROM securities WHERE isin = :isin');
        $stmt->execute(['isin' => $isin]);
        $id = $stmt->fetchColumn();

        return $id !== false ? (int) $id : null;
    }

    /**
     * Точное (после нормализации) сопоставление по названию — только
     * когда ИНН взять неоткуда (см. класс-докблок). Индекс "нормализованное
     * имя => id" строится один раз при первом обращении и держится в
     * памяти на весь прогон (эмитентов около полутысячи — недорого).
     * Неоднозначное совпадение (два разных эмитента дали одно и то же
     * нормализованное имя) — намеренно НЕ сопоставляем ни с одним из
     * них, это тоже "не нашли", а не "повезло угадать".
     */
    public function findIssuerIdByName(string $rawName): ?int
    {
        $normalized = self::normalizeCompanyName($rawName);
        if ($normalized === '') {
            return null;
        }

        if ($this->nameIndex === null) {
            $this->nameIndex = $this->buildNameIndex();
        }

        $id = $this->nameIndex[$normalized] ?? null;

        return $id === -1 ? null : $id;
    }

    /** @return array<string, int> нормализованное имя => id (-1 = неоднозначно, несколько эмитентов дали одно имя) */
    private function buildNameIndex(): array
    {
        $index = [];
        $stmt = $this->db->query('SELECT id, full_name, short_name FROM issuers');
        foreach ($stmt->fetchAll() as $row) {
            foreach ([$row['full_name'], $row['short_name']] as $name) {
                $normalized = self::normalizeCompanyName((string) $name);
                if ($normalized === '') {
                    continue;
                }
                if (isset($index[$normalized]) && $index[$normalized] !== (int) $row['id']) {
                    $index[$normalized] = -1;
                    continue;
                }
                $index[$normalized] = (int) $row['id'];
            }
        }

        return $index;
    }

    /**
     * Третий, последний уровень сопоставления — по "корню" названия,
     * когда не помогли ни ИНН, ни точное имя (см. запрос пользователя,
     * сентябрь 2026): в issuers может быть заведена только SPV-«прокладка»
     * для выпуска долга (например, «Ростелеком Финанс»), а источник
     * (заголовок новости / официальный список агентства) называет только
     * материнскую операционную компанию («Ростелеком») — и наоборот, в
     * issuers может стоять материнская компания, а источник — называть
     * SPV. Поверх обычной нормализации (см. normalizeCompanyName()) здесь
     * ещё снимаются типовые маркерные слова SPV (self::ROOT_MARKER_WORDS)
     * — и как отдельное слово, и как слитный суффикс ("ГазпромКапитал" →
     * "Газпром"). Применяется СИММЕТРИЧНО к обеим сторонам сравнения (и к
     * кандидату из источника, и к issuers.full_name/short_name в индексе
     * ниже) — поэтому ловит совпадение независимо от того, с какой
     * стороны стоит SPV, а с какой — материнская компания.
     *
     * Самый неточный из трёх уровней сопоставления в проекте — короткий
     * "корень" (short: rootCompanyName()) не считается вообще, а
     * неоднозначность (см. buildRootIndex()) — та же политика, что и у
     * findIssuerIdByName(): не угадываем.
     */
    public function findIssuerIdByRootName(string $rawName): ?int
    {
        $root = self::rootCompanyName($rawName);
        if ($root === '') {
            return null;
        }

        if ($this->rootIndex === null) {
            $this->rootIndex = $this->buildRootIndex();
        }

        $id = $this->rootIndex[$root] ?? null;

        return $id === -1 ? null : $id;
    }

    /** @return array<string, int> "корень" названия => id (-1 = неоднозначно, несколько эмитентов дали один корень) */
    private function buildRootIndex(): array
    {
        $index = [];
        $stmt = $this->db->query('SELECT id, full_name, short_name FROM issuers');
        foreach ($stmt->fetchAll() as $row) {
            foreach ([$row['full_name'], $row['short_name']] as $name) {
                $root = self::rootCompanyName((string) $name);
                if ($root === '') {
                    continue;
                }
                if (isset($index[$root]) && $index[$root] !== (int) $row['id']) {
                    $index[$root] = -1;
                    continue;
                }
                $index[$root] = (int) $row['id'];
            }
        }

        return $index;
    }

    /**
     * normalizeCompanyName() (снятие ОПФ/кавычек/регистра) плюс снятие
     * маркерных слов SPV — целиком, если слово ЦЕЛИКОМ маркер ("Ростелеком
     * Финанс" → токен "ФИНАНС" отбрасывается целиком), либо как суффикс
     * внутри слитного слова ("ГазпромКапитал" → отрезаем "КАПИТАЛ",
     * остаётся "ГАЗПРОМ"). Результат короче self::MIN_ROOT_LENGTH считается
     * ненадёжным и не используется вовсе (возвращается '').
     */
    public static function rootCompanyName(string $name): string
    {
        $normalized = self::normalizeCompanyName($name);
        if ($normalized === '') {
            return '';
        }

        $tokens = preg_split('/\s+/u', $normalized, -1, PREG_SPLIT_NO_EMPTY) ?: [];
        $result = [];
        foreach ($tokens as $token) {
            foreach (self::ROOT_MARKER_WORDS as $marker) {
                if ($token === $marker) {
                    continue 2;
                }
                $markerLen = mb_strlen($marker);
                $tokenLen = mb_strlen($token);
                if ($tokenLen > $markerLen && mb_substr($token, -$markerLen) === $marker) {
                    $token = mb_substr($token, 0, $tokenLen - $markerLen);
                    break;
                }
            }
            $result[] = $token;
        }

        $root = trim(implode(' ', $result));

        return mb_strlen($root) >= self::MIN_ROOT_LENGTH ? $root : '';
    }

    /**
     * Кавычки, организационно-правовая форма и регистр — не то, на что
     * должно влиять совпадение ("АО МФК «МК»" из новости и "Общество с
     * ограниченной ответственностью..." — не тот случай, тут просто
     * убираем шум вокруг одного и того же имени "МК"/"MK", а не пытаемся
     * угадывать ОПФ). Список форм — только реально встречавшиеся в
     * новостях/issuers.full_name на практике, не исчерпывающий справочник
     * всех форм из ГК РФ.
     *
     * Полностью прописанные формы ("Публичное акционерное общество",
     * "Общество с ограниченной ответственностью" и т.п., а не только их
     * аббревиатуры) — по прямому запросу пользователя (сентябрь 2026):
     * `issuers.full_name` из MOEX ISS часто хранит именно ПОЛНУЮ форму
     * (см. SecuritiesImporter), а не аббревиатуру. Вместо второго,
     * дублирующего словаря здесь переиспользуется уже готовый и
     * протестированный IssuerNameShortener::shorten() (тот же словарь
     * ОПФ, что и у issuers.short_name) — он ПЕРВЫМ шагом сворачивает
     * любую узнанную полную форму (в начале строки ИЛИ хвостом в
     * скобках, см. её докблок) в аббревиатуру, которую уже штатно снимает
     * regex ниже. Идемпотентно для уже абревиатурных/уже коротких
     * названий — если распознавать нечего, shorten() возвращает строку
     * без изменений.
     *
     * В regex ниже добавлена НПАО (её словарь тоже умеет отдавать) — но
     * НЕ добавлена МК ("международная компания"): это ровно тот же риск,
     * что уже описан в начале этого докблока на примере "«МК»" — короткий
     * 2-буквенный токен слишком вероятно совпадёт с чьим-то настоящим
     * названием/тикером (в отличие от "ООО"/"ПАО" и т.п.), а отличить "МК
     * как результат сокращения ОПФ" от "МК как чьё-то реальное название"
     * на этом шаге уже невозможно. Цена ошибки — не "форма не снялась"
     * (как сейчас для "международная компания"), а "два разных эмитента
     * молча схлопнулись в один", что здесь недопустимо.
     */
    public static function normalizeCompanyName(string $name): string
    {
        $name = mb_strtoupper(IssuerNameShortener::shorten(trim($name)));
        $name = str_replace(['«', '»', '"', '„', '“', '(', ')'], '', $name);
        $name = preg_replace(
            '/\b(ООО|ОАО|ЗАО|ПАО|НПАО|АО|АКБ|ПАО\s+БАНК|БАНК|ГК|ХК|НКО|МКК|МФК|КБ|ГРУППА)\b\.?/u',
            '',
            $name
        ) ?? $name;
        $name = preg_replace('/\s+/u', ' ', $name) ?? $name;

        return trim($name);
    }

    /**
     * Excel часто хранит ИНН как число, а не текст — тогда ведущий 0
     * (у ИНН, начинающихся с кода региона 01-09) молча теряется при
     * экспорте. Подтверждено на реальной выгрузке НРА (2 из 935 строк,
     * см. STAGE3_RATINGS.md): длина 9 вместо 10. Возвращаем один ведущий
     * ноль назад; если и после этого длина не 10 (юрлицо) и не 12
     * (ИП) — считаем ИНН нераспознанным, а не гадаем дальше.
     */
    public static function normalizeInn(?string $rawInn): ?string
    {
        if ($rawInn === null) {
            return null;
        }

        $digits = preg_replace('/\D/', '', $rawInn) ?? '';
        if ($digits === '') {
            return null;
        }

        if (strlen($digits) === 9 || strlen($digits) === 11) {
            $digits = '0' . $digits;
        }

        return in_array(strlen($digits), [10, 12], true) ? $digits : null;
    }
}
