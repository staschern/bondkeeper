<?php

declare(strict_types=1);

namespace BondKeeper\Ratings;

/**
 * Чистый (без обращений к БД/сети) разбор текста пресс-релизов НКР —
 * вынесен из NkrNewsImporter отдельным классом по двум причинам:
 *
 *   1. Тестируемость: все методы статические и детерминированные (голый
 *      текст на входе → структура на выходе), их можно юнит-тестировать
 *      и прогонять на реальных заголовках без БД и без сети.
 *   2. Переиспользование: bin/simulate_nkr_news.php использует ровно
 *      этот же класс, чтобы "прогон вживую" в терминале и то, что
 *      реально пишет в БД NkrNewsImporter, разбирали заголовки ОДНИМ
 *      и тем же кодом, а не двумя параллельными копиями логики, которые
 *      могут разойтись.
 *
 * NkrNewsImporter отвечает за то, что этот класс сознательно не делает:
 * сопоставление с issuers.id (нужна БД — см. IssuerMatcher) и запись в
 * rating_actions (нужна БД — см. RatingActionsWriter).
 *
 * Два метода, изначально жившие здесь (isNonStandardRating(),
 * extractQuotedNames()), переехали в RatingsNormalizer, когда та же
 * логика понадобилась Эксперт РА (сентябрь 2026) — ничего специфичного
 * для НКР в них не было, только общая проверка текста заголовка.
 */
final class NkrTitleParser
{
    /**
     * Глаголы, которыми НКР начинает заголовок рейтингового действия
     * ("НКР повысило кредитный рейтинг ..."). Список закрытый — заголовки
     * НКР очень регулярны, других глаголов в этой позиции на практике не
     * встречалось (см. docs/STAGE3_RATINGS.md).
     *
     * "изменило" добавлено по решению пользователя (сентябрь 2026) —
     * ради заголовков вида "НКР изменило прогноз по кредитному рейтингу
     * ООО «Х» на «рейтинг на пересмотре с возможностью понижения»", где
     * сам грейд не называется вообще (см. NkrNewsImporter::importRow() —
     * для этого глагола rating_to при отсутствии грейда в заголовке
     * берётся из current_ratings.rating, а не считается ошибкой разбора).
     */
    public const VERBS = ['повысило', 'снизило', 'подтвердило', 'отозвало', 'присвоило', 'изменило'];

    /** Корни слов прогноза в тексте НКР, включая "неопределённый" (→ indefinite, отдельный код — миграция 026). */
    private const OUTLOOK_WORD = '(?:позитивн|положительн|негативн|отрицательн|стабильн|развивающ|неопределённ|неопределенн)[а-яё]*';

    /** Часть предложения без конца предложения: точка внутри "A.ru"/"ВЭБ.РФ" допустима, точка перед пробелом — нет. */
    private const SAME_SENTENCE = '(?:[^.;]|\.(?!\s))*?';

    /**
     * Заголовок должен начинаться с "НКР <глагол>" — иначе это не
     * рейтинговое действие в привычном формате (например, методическая
     * новость агентства, не про конкретного эмитента).
     */
    public static function matchVerb(string $title): ?string
    {
        if (!preg_match('/^НКР\s+(' . implode('|', self::VERBS) . ')\s/u', $title, $m)) {
            return null;
        }

        return $m[1];
    }

    /**
     * Заголовок действительно про КРЕДИТНЫЙ рейтинг эмитента, а не про
     * что-то ещё, что НКР тоже публикует под тем же разделом (ESG-мнения,
     * верификации облигаций и т.п.).
     */
    public static function isCreditRatingAction(string $title): bool
    {
        return (bool) preg_match('/кредитн\w+\s+рейтинг/ui', $title);
    }

    /**
     * @return array{0: ?string, 1: ?string} [rating_from, rating_to]
     */
    public static function extractRatingChange(string $title, string $verb): array
    {
        if ($verb === 'отозвало') {
            // Отзыв — обычно без указания конкретного уровня в заголовке
            // ("и прогноз по нему без подтверждения" / "в связи с его
            // погашением"): пишем это как факт отзыва, тот же приём,
            // что уже используется для current_ratings.rating='отозван'
            // у Эксперт РА — честный текстовый статус, не выдуманный грейд.
            return [null, 'отозван'];
        }

        // Реальный найденный на живом сайте кейс (сентябрь 2026):
        // "...снизило кредитный рейтинг ООО «Бизнес-Лэнд» с CC.ru до D" —
        // дефолтный грейд "D" (и, предположительно, "SD" — выборочный
        // дефолт, по аналогии с обычной терминологией нацшкал) НКР пишет
        // БЕЗ суффикса ".ru", в отличие от всех остальных грейдов. Без
        // этой ветки "с X до Y" не находил второй грейд вообще (регэксп
        // ниже требует ".ru") и rating_to ошибочно оставался равен
        // СТАРОМУ значению (единственному найденному грейду). Проверяем
        // "D"/"SD" отдельным словом (\b), регистрозависимо (только
        // заглавные — в остальном тексте заголовка строчных "d"/"sd"
        // как отдельных слов не ожидается).
        preg_match_all('/([A-Za-zА-Яа-яЁё]{1,4}[+\-]?\.ru|\bSD\b|\bD\b)/u', $title, $m);
        $grades = $m[1];
        if ($grades === []) {
            return [null, null];
        }

        if (count($grades) >= 2 && preg_match('/\sс\s.+?\sдо\s/u', $title)) {
            return [$grades[0], $grades[1]];
        }

        // Несколько уровней без "с X до Y" — обычно относится к разным
        // лицам в одном заголовке (компания + её облигации на другом
        // уровне). Берём первый — как правило, это уровень главного,
        // первым названного в заголовке лица.
        return [null, $grades[0]];
    }

    /**
     * ИНН рейтингуемого лица со страницы конкретного пресс-релиза —
     * в блоке "Регуляторное раскрытие": "Идентификационный номер
     * налогоплательщика (ИНН) рейтингуемого лица <10-12 цифр>". Даёт ИНН
     * только ПЕРВОГО (главного, операционного) лица из заголовка — если
     * в заголовке есть второе (SPV), его ИНН на странице нет, см.
     * NkrNewsImporter::resolveIssuerIds().
     */
    public static function extractInnFromDetailHtml(string $html): ?string
    {
        $text = self::htmlToPlainText($html);

        if (preg_match('/Идентификационный номер налогоплательщика\s*\(ИНН\)\s*рейтингуемого лица\s*(\d{10,12})/u', $text, $m)) {
            return $m[1];
        }

        return null;
    }

    /**
     * Прогноз из текста действия НКР — заголовка или вводного абзаца
     * пресс-релиза (extractLeadFromDetailHtml()). Найдено вживую (сентябрь
     * 2026, АО «ГИДРОМАШСЕРВИС»): заголовок "НКР снизило кредитные рейтинги
     * АО «ГИДРОМАШСЕРВИС» и его облигаций с A+.ru до A.ru" прогноз не
     * называет, а первое предложение текста — называет ("…и изменило
     * прогноз по кредитному рейтингу со стабильного на негативный").
     * Порядок:
     *   1. Изменение прогноза — берётся то, что ПОСЛЕ "на": "со стабильного
     *      на негативный" → negative, "с позитивного на стабильный" →
     *      stable, "на «рейтинг на пересмотре …»" → статус пересмотра. Раньше
     *      заголовок "с негативного на стабильный" прочитался бы как
     *      negative (слово "негативн" проверялось раньше "стабильн").
     *   2. Статус "на пересмотре" без изменения — extractReviewStatusFromProse()
     *      ("— неопределённый прогноз" → under_review_indefinite).
     *   3. Иначе — слово прогноза в тексте ("со стабильным прогнозом",
     *      "прогноз — стабильный", "остался стабильным"). Если слов с РАЗНЫМ
     *      значением несколько (две компании в одном действии с разными
     *      прогнозами) — не угадываем, NULL.
     * NULL — прогноз не назван; вызывающий код оставляет прежний.
     * Проверено на 120 реальных релизах НКР (июнь–сентябрь 2026): на
     * заголовках результат совпал с прежней логикой во всех случаях.
     */
    public static function extractOutlook(string $text): ?string
    {
        $lower = mb_strtolower($text);

        if (preg_match('/прогноз' . self::SAME_SENTENCE . '\sна\s+«?\s*(рейтинг\s+на\s+пересмотре[^»]*)/u', $lower, $m)) {
            return RatingsNormalizer::extractReviewStatusFromProse($m[1]);
        }
        if (preg_match('/прогноз' . self::SAME_SENTENCE . '\sна\s+(' . self::OUTLOOK_WORD . ')/u', $lower, $m)) {
            return RatingsNormalizer::mapOutlookFromProse($m[1]);
        }

        $review = RatingsNormalizer::extractReviewStatusFromProse($lower);
        if ($review !== null) {
            return $review;
        }

        preg_match_all('/' . self::OUTLOOK_WORD . '/u', $lower, $m);
        $found = array_values(array_unique(array_map(
            static fn (string $word): ?string => RatingsNormalizer::mapOutlookFromProse($word),
            $m[0],
        )));

        return count($found) === 1 ? $found[0] : null;
    }

    /**
     * Вводный абзац пресс-релиза: первое предложение "Рейтинговое агентство
     * НКР <глагол> …" и, если следующее предложение начинается со слова
     * "Прогноз", — оно тоже (реальный случай ООО «Инвест КЦ»: "…с A.ru до
     * BBB+.ru. Прогноз по кредитному рейтингу ООО «Инвест КЦ» остался
     * стабильным."). Дальше в тексте прогноз не ищем: там история рейтинга
     * ("рейтинг A+.ru стабильный"), прошлые статусы и обороты вроде
     * "положительное влияние на оценку…", а у отзыва — "до момента отзыва
     * действовал рейтинг … со стабильным прогнозом".
     */
    public static function extractLeadFromDetailHtml(string $html): ?string
    {
        $text = self::htmlToPlainText($html);
        $end = '\.(?=\s+[А-ЯЁA-Z«"]|\s*$)';

        if (!preg_match('/Рейтинговое агентство НКР\s+[а-яё]+\s.{10,1200}?' . $end . '/u', $text, $m, PREG_OFFSET_CAPTURE)) {
            return null;
        }
        $lead = $m[0][0];

        $rest = ltrim(substr($text, $m[0][1] + strlen($lead)));
        if (preg_match('/^Прогноз\s.{5,400}?' . $end . '/u', $rest, $next)) {
            $lead .= ' ' . $next[0];
        }

        return $lead;
    }

    private static function htmlToPlainText(string $html): string
    {
        $html = preg_replace('/<(script|style)\b.*?<\/\1>/su', ' ', $html) ?? $html;
        $text = preg_replace('/<[^>]+>/', ' ', $html) ?? $html;
        $text = str_replace("\u{00A0}", ' ', html_entity_decode($text, ENT_QUOTES | ENT_HTML5, 'UTF-8'));

        return trim(preg_replace('/\s+/u', ' ', $text) ?? $text);
    }
}
