<?php

declare(strict_types=1);

namespace BondKeeper\Iss;

/**
 * issuers.short_name из issuers.full_name — сокращение организационно-
 * правовой формы (ОПФ) по словарю (задан пользователем, 11 сентября
 * 2026). Причина: ISS Мосбиржи (`/iss/securities.json?q=...`) отдаёт
 * только ОДНО текстовое поле имени эмитента — `emitent_title` — из-за
 * чего `SecuritiesImporter::resolveOrCreateIssuer()` раньше клал одно и
 * то же длинное название в `full_name` И `short_name` (диагностировано
 * ещё в `documents/2026.08.10_BondKeeper_issuers_securities_QA.md`).
 * Из-за этого в Telegram-боте (листалка/поиск эмитентов, см.
 * `docs/BOT_UX_SPEC.md`) длинные названия не помещались в одну строку
 * кнопки — по ним было не понять, что за компания.
 *
 * Альтернатива — DaData (`data.name.short_with_opf` из ЕГРЮЛ,
 * официальный источник, тот же вызов уже нужен для `ogrn`/`okved`, см.
 * документ выше) — обсуждалась и ОСОЗНАННО ОТКЛОНЕНА пользователем на
 * сейчас: требует регистрации/API-ключа/сети, а этот разбор работает
 * сразу и бесплатно, без внешних зависимостей. Если на реальных данных
 * качество не устроит — вернуться к DaData, ничего не потеряно (это не
 * взаимоисключающие решения, DaData можно подключить позже поверх).
 *
 * Алгоритм: с НАЧАЛА строки жадно снимаем известные словосочетания ОПФ
 * (регистр не важен — сравнение через mb_strtolower), заменяя каждое на
 * аббревиатуру, пока строка не перестанет начинаться с узнаваемого
 * словосочетания. То, что осталось (обычно название в кавычках),
 * переносится БЕЗ ИЗМЕНЕНИЙ — регистр, кавычки, всё как в источнике,
 * это и есть настоящее название компании, трогать его не наше дело.
 * Комбинации (например, "Международная компания публичное акционерное
 * общество") сворачиваются в несколько аббревиатур подряд ("МК ПАО") —
 * ровно в том порядке, в каком слова шли в оригинале, а не в
 * захардкоженном фиксированном порядке.
 *
 * Второй реальный формат ИСС (найдено на боевых данных 13 сентября 2026,
 * не было в исходном пакете от 11 сентября — тестовые примеры покрывали
 * только ОПФ-в-начале): некоторые эмитенты (например, Газпромбанк —
 * `"Газпромбанк" (Акционерное общество)`) отдают ОПФ НЕ префиксом, а
 * хвостом в скобках. Если в начале строки не узнано ничего —
 * дополнительно проверяем именно этот случай (matchTrailingLegalForm()):
 * "«Название» (ОПФ)" → "ОПФ «Название»" — тот же словарь LEGAL_FORMS, та
 * же логика "не узнано — не трогаем".
 *
 * Известное неидеальное исключение — АЛРОСА: `Акционерная компания
 * "АЛРОСА" (публичное акционерное общество)` — ведущая фраза "акционерная
 * компания" не в словаре (это отдельная, редкая историческая ОПФ, не то
 * же самое, что "акционерное общество"), поэтому даёт `ПАО Акционерная
 * компания "АЛРОСА"` — короче оригинала и с абревиатурой впереди, но не
 * идеально. Осознанно не добавляем "акционерная компания" в словарь без
 * отдельного решения пользователя — это не входило в исходный список.
 *
 * Если НИЧЕГО не узнано ни в начале, ни в конце строки — возвращаем
 * исходную строку целиком без изменений (иностранные SPV вроде "RZD
 * Capital P.L.C.", служебные заглушки вида "MOEX-12345"/"Неизвестный
 * эмитент" из SecuritiesImporter при отсутствии emitent_title) — не
 * гадать лучше, чем сломать название, которого нет в словаре.
 */
final class IssuerNameShortener
{
    /**
     * Словосочетание (нижний регистр, одиночные пробелы) => аббревиатура.
     * Порядок в массиве значения не имеет для корректности (сравнение
     * всегда идёт от начала ОСТАВШЕЙСЯ строки, а среди словосочетаний
     * нет двух с одинаковым первым словом, кроме "государственная
     * компания"/"государственная корпорация" — они не конфликтуют между
     * собой, расходятся сразу на втором слове).
     *
     * @var array<string, string>
     */
    private const LEGAL_FORMS = [
        'публичное акционерное общество' => 'ПАО',
        'непубличное акционерное общество' => 'НПАО',
        'закрытое акционерное общество' => 'ЗАО',
        'акционерное общество' => 'АО',
        'общество с ограниченной ответственностью' => 'ООО',
        'государственная корпорация' => 'ГК',
        'государственная компания' => 'ГК',
        'международная компания' => 'МК',
        'министерство финансов' => 'Минфин',
    ];

    public static function shorten(string $fullName): string
    {
        $remaining = trim(preg_replace('/\s+/u', ' ', $fullName) ?? $fullName);
        $abbreviations = [];

        while (true) {
            $match = self::matchLeadingLegalForm($remaining);
            if ($match === null) {
                break;
            }
            [$matchedLength, $abbreviation] = $match;
            $abbreviations[] = $abbreviation;
            $remaining = ltrim(mb_substr($remaining, $matchedLength));
        }

        if ($abbreviations !== []) {
            return $remaining !== ''
                ? implode(' ', $abbreviations) . ' ' . $remaining
                : implode(' ', $abbreviations);
        }

        // Ничего не нашли В НАЧАЛЕ строки — проверяем реальный, живьём
        // подтверждённый второй формат ИСС: "«Название» (ОПФ)" вместо
        // "ОПФ «Название»" (например, Газпромбанк: `"Газпромбанк"
        // (Акционерное общество)` — без этой ветки строка осталась бы
        // нетронутой целиком, хотя ОПФ прямо в ней узнаваема, просто в
        // конце, а не в начале).
        $trailing = self::matchTrailingLegalForm($remaining);
        if ($trailing !== null) {
            [$base, $abbreviation] = $trailing;

            return $base !== '' ? "{$abbreviation} {$base}" : $abbreviation;
        }

        // Ничего не узнали ни в начале, ни в конце — исходная строка
        // (не $remaining, вдруг где-то по пути схлопнули двойные пробелы
        // иначе, чем было).
        return $fullName;
    }

    /**
     * @return array{0: string, 1: string}|null [строка без хвостовой
     *   "(ОПФ)" и обрамляющих пробелов, аббревиатура]
     */
    private static function matchTrailingLegalForm(string $remaining): ?array
    {
        if (!preg_match('/\(([^()]+)\)\s*$/u', $remaining, $m)) {
            return null;
        }
        $phrase = mb_strtolower(trim($m[1]));
        if (!isset(self::LEGAL_FORMS[$phrase])) {
            return null;
        }
        $base = trim(mb_substr($remaining, 0, mb_strlen($remaining) - mb_strlen($m[0])));

        return [$base, self::LEGAL_FORMS[$phrase]];
    }

    /** @return array{0: int, 1: string}|null [длина совпавшего словосочетания в $remaining, аббревиатура] */
    private static function matchLeadingLegalForm(string $remaining): ?array
    {
        foreach (self::LEGAL_FORMS as $phrase => $abbreviation) {
            $length = mb_strlen($phrase);
            if (mb_strtolower(mb_substr($remaining, 0, $length)) !== $phrase) {
                continue;
            }
            // Граница слова — следующий символ не должен быть буквой,
            // иначе "общество" зацепит начало слова "обществоведение"
            // (гипотетически; в названиях компаний не встречается, но
            // проверка дешёвая и снимает класс ошибок целиком).
            $boundaryChar = mb_substr($remaining, $length, 1);
            if ($boundaryChar !== '' && preg_match('/[\p{L}]/u', $boundaryChar) === 1) {
                continue;
            }

            return [$length, $abbreviation];
        }

        return null;
    }
}
